import { chromium, expect } from '@playwright/test'
import fs from 'node:fs/promises'
import path from 'node:path'

const output = path.resolve('docs/evidence/m1-c1c/production-ui')
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const report = { url: 'http://127.0.0.1:4173/sceneweave/#layers', browser: browser.version(), viewport: { width: 1512, height: 982 }, errors: [], consoleErrors: [], httpErrors: [], screenshots: [] }
try {
  const page = await browser.newPage({ viewport: report.viewport, deviceScaleFactor: 1 })
  page.on('pageerror', error => report.errors.push(error.message))
  page.on('console', event => { if (event.type() === 'error') report.consoleErrors.push({ text: event.text(), url: event.location().url }) })
  page.on('response', response => { if (response.status() >= 400) report.httpErrors.push({ url: response.url(), status: response.status() }) })
  await page.goto(report.url)
  report.productDevApisAbsent = await page.evaluate(() => ['__sceneweavePerformance', '__sceneweaveAssetsDev', '__sceneweaveLayersDev'].every(key => !Reflect.has(window, key)))
  expect(report.productDevApisAbsent).toBe(true)
  await page.getByRole('button', { name: /书房与露台/ }).click()
  await page.getByRole('button', { name: '保存并打开副本', exact: true }).click()
  await expect(page.locator('.asset-save')).toHaveText('本地已保存')
  await expect(page.locator('.asset-map-wrap')).toHaveAttribute('aria-busy', 'false')
  await page.getByRole('button', { name: '新建用户图层', exact: true }).click()
  await page.getByRole('textbox', { name: '新图层名称', exact: true }).fill('家具与陈设')
  await page.getByRole('button', { name: '创建图层', exact: true }).click()
  const target = await page.getByRole('button', { name: '设为当前图层 家具与陈设', exact: true }).locator('..').locator('..').getAttribute('data-layer-id')
  await page.getByRole('group', { name: '场景对象分类', exact: true }).getByRole('button', { name: '物件', exact: true }).click()
  await page.getByLabel('搜索场景物件', { exact: true }).fill('study-chair')
  await page.locator('[data-entity-id="study-chair"]').click()
  await page.getByRole('button', { name: '更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '移动所选到图层…', exact: true }).click()
  await page.getByLabel('图层操作目标', { exact: true }).selectOption(target)
  report.expandedMoveIds = (await page.getByLabel('图层操作完整 ID', { exact: true }).inputValue()).split('\n')
  expect(report.expandedMoveIds).toContain('study-group')
  await page.getByRole('button', { name: '预览图层修改', exact: true }).click()
  await page.getByRole('button', { name: '采用图层修改', exact: true }).click()
  await page.getByRole('button', { name: '设为当前图层 家具与陈设', exact: true }).click()
  await page.getByLabel('搜索场景物件', { exact: true }).fill('')
  await expect(page.locator('.asset-save')).toHaveText('本地已保存')
  await expect(page.locator('.asset-map-wrap')).toHaveAttribute('aria-busy', 'false')
  await page.waitForFunction(() => Number(document.querySelector('.asset-viewport')?.getAttribute('data-refinement-count')) > 0)
  await page.screenshot({ path: path.join(output, 'layers-study.png') })
  report.screenshots.push('layers-study.png')
  const beforeRevision = await page.getByTestId('layer-workbench').getAttribute('data-revision')
  await page.getByRole('button', { name: '隐藏图层 家具与陈设', exact: true }).click()
  await expect(page.locator('.asset-map-wrap')).toHaveAttribute('aria-busy', 'false')
  await expect(page.getByLabel('地图视口', { exact: true })).toHaveAttribute('data-selected-ids', '[]')
  expect(await page.getByTestId('layer-workbench').getAttribute('data-revision')).toBe(beforeRevision)
  await page.screenshot({ path: path.join(output, 'layers-hidden.png') })
  report.screenshots.push('layers-hidden.png')
  report.revisionUnchangedByHiding = true
  expect(report.errors).toEqual([])
  expect(report.consoleErrors.filter(event => !event.url.endsWith('/favicon.ico'))).toEqual([])
  expect(report.httpErrors.filter(event => !event.url.endsWith('/favicon.ico') || event.status !== 404)).toEqual([])
  report.status = 'passed'
} finally {
  report.finishedAt = new Date().toISOString()
  await fs.writeFile(path.join(output, 'report.json'), JSON.stringify(report, null, 2))
  await browser.close()
}
