import { chromium, expect } from '@playwright/test'
import { createHash } from 'node:crypto'
import fs from 'node:fs/promises'
import path from 'node:path'
import { strFromU8, unzipSync } from 'fflate'

const output = path.resolve('docs/evidence/m1-c1d/production-ui')
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const report = { url: 'http://127.0.0.1:4173/sceneweave/#history', browser: browser.version(), viewport: { width: 1512, height: 982 }, errors: [], consoleErrors: [], httpErrors: [], screenshots: [] }
const hash = bytes => createHash('sha256').update(bytes).digest('hex')
try {
  const page = await browser.newPage({ viewport: report.viewport, deviceScaleFactor: 1 })
  page.on('pageerror', error => report.errors.push(error.message))
  page.on('console', event => { if (event.type() === 'error') report.consoleErrors.push({ text: event.text(), url: event.location().url }) })
  page.on('response', response => { if (response.status() >= 400) report.httpErrors.push({ url: response.url(), status: response.status() }) })
  const settled = async () => {
    await expect(page.locator('.asset-save')).toHaveText('本地已保存')
    await expect(page.locator('.asset-map-wrap')).toHaveAttribute('aria-busy', 'false')
  }
  const revision = async () => Number(await page.getByTestId('history-workbench').getAttribute('data-revision'))
  const shot = async (name, fullPage = false) => {
    await page.screenshot({ path: path.join(output, name), fullPage })
    report.screenshots.push(name)
  }
  await page.goto(report.url)
  report.productDevApisAbsent = await page.evaluate(() => ['__sceneweavePerformance', '__sceneweaveAssetsDev', '__sceneweaveLayersDev', '__sceneweaveHistoryDev'].every(key => !Reflect.has(window, key)))
  expect(report.productDevApisAbsent).toBe(true)
  await page.getByRole('button', { name: /书房与露台/ }).click()
  await page.getByRole('button', { name: '保存并打开副本', exact: true }).click()
  await settled()
  report.initialRevision = await revision()
  await page.getByRole('button', { name: '命名历史快照', exact: true }).click()
  await page.getByRole('button', { name: '新建命名快照', exact: true }).click()
  await page.getByLabel('命名快照名称', { exact: true }).fill('露台陈设 · 初稿')
  await page.getByRole('button', { name: '保存快照', exact: true }).click()
  await expect(page.getByRole('button', { name: '查看快照 露台陈设 · 初稿', exact: true })).toBeVisible()
  expect(await revision()).toBe(report.initialRevision)
  await page.getByRole('tab', { name: '场景', exact: true }).click()
  await page.getByRole('group', { name: '场景对象分类', exact: true }).getByRole('button', { name: '物件', exact: true }).click()
  await page.getByLabel('搜索场景物件', { exact: true }).fill('terrace-flowerpot')
  await page.locator('[data-entity-id="terrace-flowerpot"]').click()
  const rotation = page.getByRole('spinbutton', { name: '物件旋转', exact: true })
  report.initialRotation = Number(await rotation.inputValue())
  await rotation.fill('35'); await rotation.press('Enter'); await settled()
  await expect(rotation).toHaveValue('35')
  await page.getByRole('button', { name: '新建用户图层', exact: true }).click()
  await page.getByRole('textbox', { name: '新图层名称', exact: true }).fill('稍后新增图层')
  await page.getByRole('button', { name: '创建图层', exact: true }).click(); await settled()
  report.beforeRestoreRevision = await revision()
  await page.getByRole('tab', { name: '历史', exact: true }).click()
  await page.getByRole('button', { name: '查看快照 露台陈设 · 初稿', exact: true }).click()
  await page.getByLabel('局部恢复模式', { exact: true }).selectOption('transform')
  await page.getByRole('checkbox', { name: '恢复物件 terrace-flowerpot', exact: true }).check()
  await page.getByRole('button', { name: '预览局部恢复 · 1 件', exact: true }).click()
  await expect(page.getByRole('status', { name: '局部恢复候选', exact: true })).toBeVisible()
  const difference = page.locator('[data-restore-change-id="terrace-flowerpot"] [data-change-field="rotationDeg"]')
  await expect(difference).toContainText('35')
  await expect(difference).toContainText(String(report.initialRotation))
  expect(await revision()).toBe(report.beforeRestoreRevision)
  await shot('history-preview-desktop.png')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => window.scrollTo(0, 0))
  report.narrowViewport = { width: 390, height: 844 }
  report.narrowDocumentWidth = await page.evaluate(() => document.documentElement.scrollWidth)
  expect(report.narrowDocumentWidth).toBeLessThanOrEqual(390)
  await shot('history-preview-narrow.png', true)
  await page.getByRole('button', { name: '取消局部恢复', exact: true }).click()
  expect(await revision()).toBe(report.beforeRestoreRevision)
  await expect(page.locator('.history-snapshot-row')).toHaveCount(1)
  report.cancelPreservesRevisionAndHistory = true
  await page.setViewportSize(report.viewport)
  await page.getByRole('button', { name: '预览局部恢复 · 1 件', exact: true }).click()
  await page.getByRole('button', { name: '保护当前并采用', exact: true }).click(); await settled()
  report.adoptedRevision = await revision()
  expect(report.adoptedRevision).toBe(report.beforeRestoreRevision + 1)
  await expect(page.locator('.history-snapshot-row')).toHaveCount(2)
  report.protectionNames = await page.getByLabel('保护快照列表', { exact: true }).locator('.history-snapshot-open strong').allTextContents()
  expect(report.protectionNames).toHaveLength(1)
  await page.getByRole('button', { name: '撤销素材编辑', exact: true }).click(); await settled()
  report.undoneRevision = await revision(); expect(report.undoneRevision).toBe(report.adoptedRevision + 1)
  await page.getByRole('button', { name: '重做素材编辑', exact: true }).click(); await settled()
  report.redoneRevision = await revision(); expect(report.redoneRevision).toBe(report.undoneRevision + 1)
  await page.getByRole('checkbox', { name: '备份携带所选快照', exact: true }).check()
  await page.getByRole('checkbox', { name: '备份快照 露台陈设 · 初稿', exact: true }).check()
  expect(await page.locator('[data-backup-snapshot-id] input:checked').count()).toBe(1)
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载工程与所选历史 · 1 份', exact: true }).click()
  const downloaded = await downloading, archive = await fs.readFile((await downloaded.path()))
  const files = unzipSync(archive), manifest = JSON.parse(strFromU8(files['manifest.json']))
  const current = JSON.parse(strFromU8(files['scene.json'])), history = JSON.parse(strFromU8(files['history.json']))
  expect(manifest.containerVersion).toBe(4); expect(manifest.documentSchemaVersion).toBe(3)
  expect(manifest.profile).toBe('m1-history'); expect(manifest.packageMode).toBe('history')
  expect(current.revision).toBe(report.redoneRevision)
  expect(current.props['terrace-flowerpot'].rotationDeg).toBe(report.initialRotation)
  expect(Object.values(current.userLayers).some(layer => layer.name === '稍后新增图层')).toBe(true)
  expect(history.snapshots.map(item => item.summary.name)).toEqual(['露台陈设 · 初稿'])
  for (const entry of manifest.entries) {
    expect(files[entry.path].length).toBe(entry.sizeBytes)
    expect(hash(files[entry.path])).toBe(entry.sha256)
  }
  const snapshot = JSON.parse(strFromU8(files[history.snapshots[0].scenePath]))
  expect(snapshot.props['terrace-flowerpot'].rotationDeg).toBe(report.initialRotation)
  expect(Object.values(snapshot.userLayers).some(layer => layer.name === '稍后新增图层')).toBe(false)
  report.backup = { bytes: archive.length, sha256: hash(archive), manifest, selectedNames: history.snapshots.map(item => item.summary.name), currentRevision: current.revision, restoredProp: current.props['terrace-flowerpot'], laterLayerRetained: true, allEntryHashesVerified: true }
  await page.evaluate(() => window.scrollTo(0, 0))
  await shot('history-adopted-desktop.png')
  expect(report.errors).toEqual([])
  expect(report.consoleErrors.filter(event => !event.url.endsWith('/favicon.ico'))).toEqual([])
  expect(report.httpErrors.filter(event => !event.url.endsWith('/favicon.ico') || event.status !== 404)).toEqual([])
  report.status = 'passed'
} catch (error) {
  report.status = 'failed'; report.failure = String(error)
  throw error
} finally {
  report.finishedAt = new Date().toISOString()
  await fs.writeFile(path.join(output, 'report.json'), JSON.stringify(report, null, 2))
  await browser.close()
}
