import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const destination = path.join(root, 'src/shared/ai/workflows/catalog.generated.ts')
const canonical = value => JSON.stringify(value && typeof value === 'object'
  ? Array.isArray(value) ? value.map(item => JSON.parse(canonical(item)))
    : Object.fromEntries(Object.keys(value).sort().map(key => [key, JSON.parse(canonical(value[key]))])) : value)
const manifest = JSON.parse(await fs.readFile(path.join(root, 'workflows/catalog.json'), 'utf8'))
if (manifest.schemaVersion !== 1 || !Array.isArray(manifest.workflows)) throw new Error('Invalid workflow manifest')
const ids = new Set(), workflows = []
for (const { bodyFile, ...metadata } of manifest.workflows) {
  if (!/^[a-z][a-z0-9-]+\.md$/.test(bodyFile) || ids.has(metadata.id)) throw new Error('Invalid or duplicate workflow source')
  ids.add(metadata.id)
  const body = (await fs.readFile(path.join(root, 'workflows', bodyFile), 'utf8')).replaceAll('\r\n', '\n')
  const sections = [...body.matchAll(/^## ([a-z][a-z0-9-]*)\n([\s\S]*?)(?=^## |$(?![\s\S]))/gm)]
  if (sections.length !== metadata.steps.length || new Set(sections.map(section => section[1])).size !== sections.length
    || new Set(metadata.steps.map(step => step.id)).size !== metadata.steps.length
    || sections.some(section => !metadata.steps.some(step => step.id === section[1]))) throw new Error(`Invalid steps in ${bodyFile}`)
  const steps = metadata.steps.map(step => {
    const instructions = sections.find(section => section[1] === step.id)?.[2].trim()
    if (!instructions) throw new Error(`Missing step ${step.id}`)
    return { ...step, instructions }
  })
  for (const effect of metadata.effects) {
    const [file, anchor] = effect.reference.split('#')
    if (!file.startsWith('docs/') || file.split('/').includes('..')) throw new Error('Invalid evidence reference')
    const evidence = await fs.readFile(path.join(root, file), 'utf8')
    if (anchor && !evidence.includes(`id="${anchor}"`)) throw new Error(`Missing evidence anchor ${effect.reference}`)
    for (const preview of effect.previews) {
      if (!/^public\/assets\/workflows\/[a-z0-9-]+\.png$/.test(preview.path)
        || !/^workflows\/examples\/[a-z0-9-]+\.json$/.test(preview.provenance)) throw new Error('Invalid workflow preview path')
      const bytes = await fs.readFile(path.join(root, preview.path))
      if (bytes.length < 24 || bytes.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a'
        || bytes.readUInt32BE(16) !== preview.width || bytes.readUInt32BE(20) !== preview.height
        || createHash('sha256').update(bytes).digest('hex') !== preview.sha256) throw new Error(`Workflow preview changed: ${preview.path}`)
      const provenance = JSON.parse(await fs.readFile(path.join(root, preview.provenance), 'utf8'))
      if (provenance.preview.sha256 !== preview.sha256 || provenance.preview.width !== preview.width || provenance.preview.height !== preview.height
        || provenance.technicalVerification.changedPixels !== 0) throw new Error('Workflow preview provenance mismatch')
    }
  }
  const definition = { ...metadata, source: `workflows/${bodyFile}`, steps }
  workflows.push({ ...definition, definitionHash: createHash('sha256').update(canonical(definition)).digest('hex') })
}
const output = '// Generated by node tools/sync-workflows.mjs; edit workflows/catalog.json and workflows/*.md.\n'
  + `export const WORKFLOW_DEFINITIONS = ${JSON.stringify(workflows, null, 2)} as const\n`
if (process.argv.slice(2).length > 1 || process.argv.slice(2).some(argument => argument !== '--check')) throw new Error('Usage: node tools/sync-workflows.mjs [--check]')
if (process.argv.includes('--check')) {
  if ((await fs.readFile(destination, 'utf8').catch(() => '')).replaceAll('\r\n', '\n') !== output) throw new Error('Shared workflow projection is stale; run node tools/sync-workflows.mjs')
  process.stdout.write(`Shared workflow sources and ${workflows.length} generated definitions match.\n`)
} else {
  await fs.mkdir(path.dirname(destination), { recursive: true })
  await fs.writeFile(destination, output)
}
