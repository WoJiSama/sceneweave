    const lib = library(page); await readyLibrary(page)
    await lib.getByLabel('搜索组件素材', { exact: true }).fill('桌灯')
    const button = lib.locator('.catalog-item-main').first()
    await expect(button).toBeVisible(); await button.focus(); await button.press('Enter')
    await lib.getByRole('button', { name: '编辑此项个人整理', exact: true }).click()
    await lib.getByLabel('个人素材标签', { exact: true }).fill('窄屏草稿')
