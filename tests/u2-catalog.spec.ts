  await expect(lib.locator('.catalog-entries article')).toHaveCount(1)
  await expect(lib.locator('.catalog-entries article')).toContainText('Ｕ２　常用')
  expect(await state(page)).toEqual(source)
  await page.getByRole('button', { name: '回到首页', exact: true }).click()
  await createBlank(page, 'U2 离线采用目标')
