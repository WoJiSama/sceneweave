  await expect(page.getByRole('button', { name: '采用组件修改', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '采用组件修改', exact: true }).click(); await settled(page)
  await lib.getByLabel('搜索组件素材', { exact: true }).fill(name)
  const row = lib.locator('.catalog-entries article').filter({ hasText: name })
  await expect(row).toHaveCount(1)
  await expect.poll(() => row.locator('img').evaluateAll(images => images.every(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth > 0) && images.length > 0)).toBe(true)
  const source = await state(page)
  await row.getByLabel(`选择素材 ${name}`, { exact: true }).check()
