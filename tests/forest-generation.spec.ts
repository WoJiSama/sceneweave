import { expect, test } from '@playwright/test'

test('forest suggestions reserve routes, save, cold-open and keep a deleted tree absent', async ({ page }, info) => {
  test.setTimeout(180_000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#home')
  await page.getByTestId('workspace-home').getByRole('button', { name: '新建场景', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '新建空白场景', exact: true })
  await dialog.getByLabel('场景名称', { exact: true }).fill('D4原工程')
  await dialog.getByRole('button', { name: '创建空白场景', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.asset-save')).toHaveText('本地已保存', { timeout: 30000 })
  await page.getByRole('tab', { name: '工程', exact: true }).click()
  const panel = page.getByRole('region', { name: '森林与营地生成', exact: true })
  await panel.getByLabel('森林工程名称').fill('D4森林营地')
  await panel.getByRole('button', { name: '预览森林与营地', exact: true }).click()
  await expect(panel.getByLabel('森林与营地候选摘要')).toContainText('1 处空地', { timeout: 30000 })
  await expect(panel.getByLabel('森林实际生成结果')).toContainText(/实际安排 [1-9]\d* 条路线、[1-9]\d* 棵树/)
  await expect(page.locator('.asset-view-actions')).toContainText('32.000 m × 24.000 m')
  await expect(page.getByLabel('材质场景主持人预览', { exact: true })).toBeVisible()
  await expect(page.locator('.asset-busy')).toHaveCount(0, { timeout: 30000 })
  await page.screenshot({ path: info.outputPath('forest-preview.png') })
  // An edit invalidates the prepared request before the next generation.
  await panel.getByLabel('空地1横向位置米').fill('10')
  await panel.getByLabel('森林入口方向').selectOption('east')
  await expect(panel.getByLabel('森林与营地候选摘要')).toHaveCount(0)
  await panel.getByRole('button', { name: '预览森林与营地', exact: true }).click()
  await expect(panel.getByLabel('森林与营地候选摘要')).toBeVisible({ timeout: 30000 })
  await expect(panel.getByLabel('森林实际生成结果')).toContainText(/实际安排 [1-9]\d* 条路线、[1-9]\d* 棵树/)
  await panel.getByRole('button', { name: '保存为新工程', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: '森林与营地已完整保存' })).toBeVisible({ timeout: 30000 })
  await expect(panel.getByLabel('森林与营地候选摘要')).toHaveCount(0)
  await expect(page.locator('.asset-save')).toHaveText('本地已保存', { timeout: 30000 })
  await page.goto('/#home')
  await page.reload()
  const row = page.getByTestId('workspace-home').locator('.home-project-row').filter({ hasText: 'D4森林营地' })
  await expect(row).toHaveCount(1, { timeout: 30000 })
  await row.getByRole('button', { name: '打开', exact: true }).click()
  await expect(page.getByLabel('材质场景主持人预览', { exact: true })).toBeVisible({ timeout: 30000 })
  await expect(page.locator('.asset-save')).toHaveText('本地已保存', { timeout: 30000 })
  await expect(page.locator('.asset-busy')).toHaveCount(0, { timeout: 30000 })
  await page.screenshot({ path: info.outputPath('forest-cold-open.png') })
  // Real tree Props use the public object inspector and normal deletion path.
  await page.getByRole('tab', { name: '对象', exact: true }).click()
  await page.getByRole('group', { name: '场景对象分类', exact: true }).getByRole('button', { name: '物件', exact: true }).click()
  const tree = page.locator('.asset-entity-list button[data-entity-id]').first()
  await expect(tree).toBeVisible()
  const deletedId = await tree.getAttribute('data-entity-id')
  expect(deletedId).toBeTruthy()
  await page.getByLabel('搜索场景物件', { exact: true }).fill(deletedId!)
  await tree.click()
  await page.getByRole('button', { name: '删除物件', exact: true }).click()
  await expect(page.locator(`.asset-entity-list [data-entity-id="${deletedId}"]`)).toHaveCount(0)
  await expect(page.locator('.asset-busy')).toHaveCount(0, { timeout: 30000 })
  await expect(page.locator('.asset-save')).toHaveText('本地已保存', { timeout: 30000 })
  await page.goto('/#home')
  await page.reload()
  const reopened = page.getByTestId('workspace-home').locator('.home-project-row').filter({ hasText: 'D4森林营地' })
  await reopened.getByRole('button', { name: '打开', exact: true }).click()
  await expect(page.getByLabel('材质场景主持人预览', { exact: true })).toBeVisible({ timeout: 30000 })
  await expect(page.locator('.asset-save')).toHaveText('本地已保存', { timeout: 30000 })
  await page.getByRole('tab', { name: '对象', exact: true }).click()
  await page.getByRole('group', { name: '场景对象分类', exact: true }).getByRole('button', { name: '物件', exact: true }).click()
  await page.getByLabel('搜索场景物件', { exact: true }).fill(deletedId!)
  await expect(page.locator(`.asset-entity-list [data-entity-id="${deletedId}"]`)).toHaveCount(0)
  await expect(page.locator('.asset-busy')).toHaveCount(0, { timeout: 30000 })
  await page.screenshot({ path: info.outputPath('forest-deleted-cold-open.png') })
  expect(errors).toEqual([])
})
