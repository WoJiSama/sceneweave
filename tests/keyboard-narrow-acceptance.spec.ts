import { expect, test, type Locator } from '@playwright/test'
import { writeFile } from 'node:fs/promises'
import { createKeyboardProject, keyboardProjectBackup, keyboardResourceHashes, keyboardWorkspaceSaved, openKeyboardPanel, placeKeyboardLamp, selectKeyboardProp } from './keyboard-ux-helpers'
import { reloadSaved } from './workspace-ux-helpers'

const viewports = [{ width: 1512, height: 982 }, { width: 900, height: 800 }, { width: 390, height: 844 }]

for (const size of viewports) test(`production keyboard and narrow acceptance at ${size.width}x${size.height}`, async ({ page, browser }, info) => {
  test.setTimeout(240000)
  await page.setViewportSize(size)
  const errors: string[] = [], focusTrace: unknown[] = []
  page.on('pageerror', error => errors.push(error.message))
  const rememberFocus = async (step: string) => {
    focusTrace.push({ step, ...await page.evaluate(() => {
      const node = document.activeElement as HTMLElement | null
      return { tag: node?.tagName, role: node?.getAttribute('role'), name: node?.getAttribute('aria-label') ?? node?.textContent?.trim().slice(0, 100), panel: node?.closest('[data-testid]')?.getAttribute('data-testid'), outline: node ? getComputedStyle(node).outlineStyle : undefined }
    }) })
  }
  const key = async (pressed: string, step: string) => { await page.keyboard.press(pressed); await rememberFocus(step) }
  const tabTo = async (target: Locator, step: string) => {
    for (let index = 0; index < 100; index++) {
      if (await target.evaluate(node => node === document.activeElement)) { await rememberFocus(step); return }
      await key('Tab', `${step}:Tab${index + 1}`)
    }
    throw new Error(`Keyboard Tab did not reach ${step}`)
  }
  const closeDrawers = async () => {
    if (size.width >= 1080) return
    for (const [id, name] of [['resources', '内容面板'], ['inspector', '当前详情']] as const) {
      const panel = page.getByTestId(`workspace-${id}`)
      if (await panel.getAttribute('data-open') === 'true') {
        await panel.getByRole('button', { name: `关闭${name}`, exact: true }).click()
        await expect(panel).toHaveAttribute('data-open', 'false')
        // Module selection and explicit detail actions now have their own return targets.
        expect(await page.evaluate(() => document.activeElement !== document.body && !document.activeElement?.closest('[hidden],[inert]'))).toBe(true)
        expect(await panel.evaluate(node => node.contains(document.activeElement))).toBe(false)
        await rememberFocus(`close ${name}`)
      }
    }
  }
  const noPageOverflow = async () => {
    const dimensions = await page.evaluate(() => ({ viewport: innerWidth, root: document.documentElement.scrollWidth, body: document.body.scrollWidth }))
    expect(dimensions.viewport).toBe(size.width)
    expect(dimensions.root).toBeLessThanOrEqual(dimensions.viewport)
    expect(dimensions.body).toBeLessThanOrEqual(dimensions.viewport)
  }

  await createKeyboardProject(page, `键盘与窄屏验收 ${size.width}`)
  await closeDrawers()
  await expect(page.getByTestId('workspace-layout')).toHaveAttribute('data-narrow', String(size.width < 1080))
  await noPageOverflow()

  // A known header anchor starts a real Tab journey through help and native export disclosure.
  await page.getByRole('button', { name: '回到首页', exact: true }).focus()
  const help = page.locator('.workspace-help > summary')
  await tabTo(help, 'help reached by Tab')
  await key('Enter', 'open help by Enter')
  const helpContents = page.getByRole('region', { name: '制作流程与快捷键', exact: true })
  await expect(helpContents).toBeVisible()
  await key('Tab', 'enter help content')
  await expect(helpContents).toBeFocused()
  await key('PageDown', 'scroll help by keyboard')
  await page.screenshot({ path: info.outputPath(`help-${size.width}.png`) })
  await key('Escape', 'close help and restore summary focus')
  await expect(help).toBeFocused()
  await expect(page.locator('.workspace-help')).not.toHaveAttribute('open')
  const exportSummary = page.locator('.workspace-export-menu > summary')
  await tabTo(exportSummary, 'export reached by Tab')
  await key('Space', 'open export by Space')
  await expect(page.getByRole('group', { name: '导出选项', exact: true })).toBeVisible()
  await key('Tab', 'export first action reached')
  await expect(page.getByRole('button', { name: '玩家地图 PNG', exact: true })).toBeFocused()
  await key('Shift+Tab', 'return to export summary')
  await expect(exportSummary).toBeFocused()
  await key('Space', 'close export by Space')
  await expect(page.locator('.workspace-export-menu')).not.toHaveAttribute('open')

  for (const [id, name] of [['resources', '内容面板'], ['inspector', '当前详情']] as const) {
    const trigger = page.getByRole('button', { name, exact: true }), panel = page.getByTestId(`workspace-${id}`)
    await tabTo(trigger, `${name} trigger reached by Tab`)
    await key('Space', `${name} toggle by Space`)
    if (size.width < 1080) {
      await expect(panel).toHaveAttribute('data-open', 'true')
      await expect(panel.getByRole('button', { name: `关闭${name}`, exact: true })).toBeFocused()
      await key('Escape', `${name} drawer Escape`)
      await expect(panel).toHaveAttribute('data-open', 'false')
      await expect(trigger).toBeFocused()
    } else {
      await expect(panel).toHaveAttribute('data-open', 'false')
      await expect(trigger).toBeFocused()
      await key('Space', `${name} reopen by Space`)
      await expect(panel).toHaveAttribute('data-open', 'true')
    }
  }

  await placeKeyboardLamp(page)
  await closeDrawers()
  const original = await keyboardProjectBackup(page, info.outputPath('keyboard-before.sceneweave'))
  const [source] = Object.values(original.document.props)
  expect(Object.keys(original.document.props)).toHaveLength(1)
  await selectKeyboardProp(page, source.id)
  const navigation = await openKeyboardPanel(page, 'navigation')
  const search = navigation.getByLabel('搜索场景对象', { exact: true })
  await search.fill('文本输入保护')
  await search.press('ControlOrMeta+A')
  await search.press('ControlOrMeta+C')
  await search.fill('')
  await search.press('ControlOrMeta+V')
  await expect(search).toHaveValue('文本输入保护')
  await search.press('Enter')
  await expect(page.getByRole('region', { name: '候选审阅', exact: true })).toHaveCount(0)
  await selectKeyboardProp(page, source.id)
  await closeDrawers()
  const viewport = page.getByRole('group', { name: '地图视口', exact: true })
  const review = page.getByTestId('workspace-inspector').getByRole('region', { name: '候选审阅', exact: true })
  const revision = page.locator('.workspace-unified')
  await expect(revision).toHaveAttribute('data-revision', String(original.document.revision))
  await viewport.focus()
  await key('Shift+F10', 'open object menu from canvas')
  const menu = page.getByRole('menu')
  await expect(menu).toBeVisible()
  await expect(menu.getByRole('menuitem').first()).toBeFocused()
  await key('Escape', 'close object menu and restore canvas focus')
  await expect(menu).toHaveCount(0)
  await expect(viewport).toBeFocused()

  await key('ControlOrMeta+C', 'copy scene selection')
  await expect(page.locator('.asset-notice')).toContainText('已复制 1 个独立物件')
  await key('ControlOrMeta+V', 'paste to candidate')
  await expect(review).toContainText('粘贴所选 · 1 个独立物件')
  await keyboardWorkspaceSaved(page)
  await expect(revision).toHaveAttribute('data-revision', String(original.document.revision))
  const cancelPaste = review.getByRole('button', { name: '取消批量预览', exact: true })
  const adoptPaste = review.getByRole('button', { name: '采用批量修改', exact: true })
  await cancelPaste.scrollIntoViewIfNeeded()
  await expect(cancelPaste).toBeInViewport({ ratio: 1 })
  await adoptPaste.scrollIntoViewIfNeeded()
  await expect(adoptPaste).toBeInViewport({ ratio: 1 })
  await page.screenshot({ path: info.outputPath(`paste-candidate-${size.width}.png`) })
  await cancelPaste.focus()
  await key('Tab', 'candidate adopt reached from cancel')
  await expect(adoptPaste).toBeFocused()
  await key('Shift+Tab', 'candidate cancel reached from adopt')
  await expect(cancelPaste).toBeFocused()
  await key('Enter', 'cancel paste with keyboard')
  await expect(review).toHaveCount(0)
  expect((await keyboardProjectBackup(page, info.outputPath('keyboard-paste-cancelled.sceneweave'))).hashes).toEqual(original.hashes)
  await viewport.focus()
  await key('ControlOrMeta+V', 'paste again for adoption')
  await expect(review).toContainText('粘贴所选 · 1 个独立物件')
  await adoptPaste.focus()
  await key('Enter', 'adopt paste with keyboard')
  await expect(review).toHaveCount(0)
  await keyboardWorkspaceSaved(page)
  const adopted = await keyboardProjectBackup(page, info.outputPath('keyboard-paste-adopted.sceneweave'))
  expect(adopted.document.revision).toBe(original.document.revision + 1)
  const [copy] = Object.values(adopted.document.props).filter(prop => prop.id !== source.id)
  expect(Object.keys(adopted.document.props)).toHaveLength(2)
  expect(copy).toEqual({ ...source, id: copy.id, renderOrder: copy.renderOrder, positionMm: { x: 4300, y: 4300 } })
  await viewport.focus()
  await key('ControlOrMeta+Z', 'undo paste as one transaction')
  await keyboardWorkspaceSaved(page)
  const undone = await keyboardProjectBackup(page, info.outputPath('keyboard-paste-undone.sceneweave'))
  expect(undone.document).toEqual({ ...original.document, revision: original.document.revision + 2, updatedAt: undone.document.updatedAt })

  await selectKeyboardProp(page, source.id)
  await closeDrawers()
  await viewport.focus()
  await key('Delete', 'preview deletion')
  await expect(review).toContainText('删除所选 · 1 个选择单元')
  await viewport.focus()
  await key('Escape', 'cancel deletion')
  await expect(review).toHaveCount(0)
  await expect(revision).toHaveAttribute('data-revision', String(undone.document.revision))
  // Cancellation swaps the preview canvas back to the saved project asynchronously.
  await keyboardWorkspaceSaved(page)

  await viewport.focus()
  const oldZoom = Number(await viewport.getAttribute('data-zoom'))
  await key('+', 'zoom canvas in')
  await expect.poll(async () => Number(await viewport.getAttribute('data-zoom'))).toBeGreaterThan(oldZoom)
  await keyboardWorkspaceSaved(page)
  const oldPan = await viewport.getAttribute('data-pan-x')
  await key('ArrowRight', 'pan canvas with arrow key')
  await expect.poll(() => viewport.getAttribute('data-pan-x')).not.toBe(oldPan)
  await keyboardWorkspaceSaved(page)
  await key('-', 'zoom canvas out')
  await keyboardWorkspaceSaved(page)
  await key('0', 'fit canvas')
  await keyboardWorkspaceSaved(page)
  await expect(revision).toHaveAttribute('data-revision', String(undone.document.revision))

  await closeDrawers()
  await page.getByRole('button', { name: '工具：画房间', exact: true }).click()
  await closeDrawers()
  const canvas = page.locator('canvas[aria-label="材质场景主持人预览"]')
  const box = await canvas.boundingBox()
  if (!box) throw new Error('Expected the real visible canvas for rectangle drawing')
  const bounds = undone.document.exportBoundsMm
  for (const point of [{ x: 7000, y: 2000 }, { x: 10000, y: 5000 }]) {
    await page.mouse.click(box.x + (point.x - bounds.x) / bounds.width * box.width, box.y + (point.y - bounds.y) / bounds.height * box.height)
  }
  await viewport.focus()
  await key('Enter', 'finish two-corner room into candidate')
  await expect(review).toContainText('新建新房间')
  await keyboardWorkspaceSaved(page)
  await expect(revision).toHaveAttribute('data-revision', String(undone.document.revision))
  const roomDetails = review.locator('details.composition-preview-details')
  await roomDetails.locator(':scope > summary').focus()
  await key('Enter', 'expand room changes with keyboard')
  await expect(roomDetails).toHaveAttribute('open', '')
  const fields = roomDetails.locator('summary').filter({ hasText: '字段与 ID 详情' }).first()
  await fields.focus()
  await key('Space', 'expand real room field details')
  const scrollSize = await review.locator('.workspace-candidate-body').evaluate(node => ({ content: node.scrollHeight, visible: node.clientHeight }))
  expect(scrollSize.content).toBeGreaterThan(scrollSize.visible)
  await noPageOverflow()
  const confirmRoom = review.getByLabel('确认完整影响范围', { exact: true })
  const adoptRoom = review.getByRole('button', { name: '采用结构修改', exact: true })
  await confirmRoom.focus()
  await key('Space', 'confirm room scope with keyboard')
  await expect(adoptRoom).toBeEnabled()
  const cancelRoom = review.getByRole('button', { name: '取消结构预览', exact: true })
  await key('Tab', 'room cancel reached from confirmation')
  await expect(cancelRoom).toBeFocused()
  await key('Tab', 'room adopt reached after expanded long details')
  await expect(adoptRoom).toBeFocused()
  await expect(adoptRoom).toBeInViewport({ ratio: 1 })
  await key('Shift+Tab', 'return to room cancel without adopting')
  await cancelRoom.scrollIntoViewIfNeeded()
  await expect(cancelRoom).toBeInViewport({ ratio: 1 })
  await page.screenshot({ path: info.outputPath(`room-candidate-${size.width}.png`) })
  await cancelRoom.focus()
  await key('Enter', 'cancel room candidate with keyboard')
  await expect(review).toHaveCount(0)
  await keyboardWorkspaceSaved(page)
  await closeDrawers()
  await page.getByRole('button', { name: '选择地图对象', exact: true }).click()
  await viewport.focus()
  await key('ControlOrMeta+S', 'save current project to browser')
  await keyboardWorkspaceSaved(page)
  await expect(revision).toHaveAttribute('data-revision', String(undone.document.revision))
  await noPageOverflow()
  const final = await keyboardProjectBackup(page, info.outputPath('keyboard-final.sceneweave'))
  expect(final.hashes).toEqual(undone.hashes)
  expect(keyboardResourceHashes(final.hashes)).toEqual(keyboardResourceHashes(original.hashes))
  await page.screenshot({ path: info.outputPath(`workspace-${size.width}.png`) })
  await reloadSaved(page)
  await keyboardWorkspaceSaved(page)
  await closeDrawers()
  const reloaded = await keyboardProjectBackup(page, info.outputPath('keyboard-reloaded.sceneweave'))
  expect(reloaded.document).toEqual(final.document)
  expect(reloaded.identity).toEqual(final.identity)
  expect(reloaded.appearance).toEqual(final.appearance)
  expect(reloaded.hashes).toEqual(final.hashes)
  await noPageOverflow()
  expect(errors).toEqual([])
  const factsPath = info.outputPath('keyboard-narrow-facts.json')
  await writeFile(factsPath, JSON.stringify({ viewport: size, browserVersion: browser.version(), focusTrace, revisions: [original.document.revision, adopted.document.revision, undone.document.revision, final.document.revision], sourceId: source.id, copiedId: copy.id, errors }, null, 2))
  await info.attach('keyboard-narrow-facts.json', { path: factsPath, contentType: 'application/json' })
})
