// Normal production UI. Read engineering facts only from actual backups.
import { expect, test, type Page, type TestInfo } from '@playwright/test'
import { writeFile } from 'node:fs/promises'
import { openWorkspaceModule, openTerrainTask } from './workspace-navigation-helpers'
import { createKeyboardProject, keyboardProjectBackup, keyboardWorkspaceSaved, openKeyboardPanel } from './keyboard-ux-helpers'

test.use({ actionTimeout: 15000 })

async function chooseBuilding(page: Page, task: '绘制房间' | '建筑组') {
  const content = await openWorkspaceModule(page, '建筑')
  await content.getByRole('group', { name: '建筑任务', exact: true }).getByRole('button', { name: new RegExp(`^${task}`) }).click()
  await expect(page.getByTestId('workspace-inspector')).toHaveAttribute('data-open', 'true')
}
async function chooseOutdoor(page: Page, task: '地形与高程' | '道路' | '台阶 / 坡道' | '可控散布') {
  const content = await openWorkspaceModule(page, '地形')
  await content.getByRole('group', { name: '室外任务', exact: true }).getByRole('button', { name: new RegExp(`^${task}`) }).click()
  await expect(page.getByTestId('workspace-inspector')).toHaveAttribute('data-open', 'true')
}
async function commit(page: Page, name: string, value: string) {
  const input = page.getByLabel(name, { exact: true })
  await input.fill(value); await input.press('Tab')
}
async function shot(page: Page, info: TestInfo, name: string) {
  const panel = page.getByTestId('workspace-inspector').locator('.workspace-panel-body')
  await panel.evaluate(node => node.scrollTo(0, 0))
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
  const size = await panel.evaluate(node => ({ client: node.clientWidth, scroll: node.scrollWidth }))
  expect(size.scroll).toBeLessThanOrEqual(size.client + 1)
  await page.screenshot({ path: info.outputPath(`${name}.png`), animations: 'disabled' })
}

