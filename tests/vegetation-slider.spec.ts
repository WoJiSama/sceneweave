import { expect, test } from '@playwright/test'
import { openGenerationTask, openTerrainTask } from './workspace-navigation-helpers'

test('vegetation coverage preserves its ppm range through pointer and keyboard edits', async ({ page }) => {
  test.setTimeout(120_000)
  await page.goto('/#workspace')
  await openGenerationTask(page, '自然地形')
  await page.getByRole('button', { name: '生成地形预览', exact: true }).click()
  const adopt = page.getByRole('button', { name: '采用当前地形方案', exact: true })
  await expect(adopt).toBeEnabled({ timeout: 90_000 }); await adopt.click()
  await expect(page.locator('.asset-busy')).toHaveCount(0, { timeout: 90_000 })
  await expect(page.locator('.asset-save')).toHaveText('本地已保存', { timeout: 90_000 })
  await openTerrainTask(page, '布置植被')
  const slider = page.getByRole('slider', { name: '区域植被目标覆盖率', exact: true })
  await expect(slider).toHaveValue('180000')
  await expect(slider).toHaveAttribute('min', '0')
  await expect(slider).toHaveAttribute('max', '1000000')
  await expect(slider).toHaveAttribute('step', '10000')
  await slider.scrollIntoViewIfNeeded()
  const box = await slider.boundingBox()
  if (!box) throw new Error('Expected a visible coverage slider')
  await page.mouse.click(box.x + box.width * .25, box.y + box.height / 2)
  const value = Number(await slider.inputValue())
  expect(value).toBeGreaterThan(100_000); expect(value).toBeLessThan(400_000)
  const output = slider.locator('..').locator('output')
  await expect(output).toHaveText(`${value / 10_000}%`)
  await slider.press('Home'); await expect(slider).toHaveValue('0'); await expect(output).toHaveText('0%')
  await slider.press('End'); await expect(slider).toHaveValue('1000000'); await expect(output).toHaveText('100%')
  await slider.press('ArrowLeft'); await expect(slider).toHaveValue('990000'); await expect(output).toHaveText('99%')
})
