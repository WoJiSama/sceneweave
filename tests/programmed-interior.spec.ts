import { expect, test } from '@playwright/test'
import { keyboardProjectBackup, keyboardWorkspaceSaved } from './keyboard-ux-helpers'
import { openGenerationTask, openSceneObjects } from './workspace-navigation-helpers'

test('the web generator saves directed entrances and edits the wide door presentation at its original width', async ({ page }, info) => {
  test.setTimeout(120_000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('./#home')
  await page.getByTestId('workspace-home').getByRole('button', { name: '生成地图', exact: true }).click()
  await openGenerationTask(page, '室内布局')
  const panel = page.getByRole('region', { name: '室内布局生成', exact: true })
  await panel.getByLabel('室内工程名称', { exact: true }).fill('社区活动室')
  await panel.getByLabel('室内建筑宽米', { exact: true }).fill('16')
  await panel.getByLabel('室内建筑高米', { exact: true }).fill('12')
  await panel.getByLabel('房间1用途', { exact: true }).fill('活动室')
  await panel.getByLabel('房间2用途', { exact: true }).fill('物资室')
  await panel.locator('summary').filter({ hasText: '详细设置 · 面积、走廊与布置' }).click()
  await panel.getByLabel('房间1最小面积', { exact: true }).fill('48')
  await panel.getByLabel('房间2最大面积', { exact: true }).fill('52')
  await panel.getByLabel('室内建议通路净宽米', { exact: true }).fill('1')
  await panel.locator('summary').filter({ hasText: '指定外门、内门与家具组' }).click()
  await panel.getByRole('button', { name: '增加外门', exact: true }).click()
  await panel.getByLabel('外门1朝向', { exact: true }).selectOption('south')
  await panel.getByLabel('外门1净宽', { exact: true }).fill('1.6')
  await panel.getByRole('button', { name: '增加外门', exact: true }).click()
  await panel.getByLabel('外门2房间', { exact: true }).selectOption('room-2')
  await panel.getByLabel('外门2朝向', { exact: true }).selectOption('north')
  await panel.getByRole('button', { name: '增加内门', exact: true }).click()
  await panel.getByLabel('内门1净宽', { exact: true }).fill('2.4')
  await panel.getByLabel('活动室桌椅组数', { exact: true }).fill('1')
  await panel.getByLabel('活动室服务台邻房', { exact: true }).selectOption('room-2')
  await panel.getByLabel('添加可编辑房间标注').check()
  await panel.getByRole('button', { name: '预览室内布局', exact: true }).click()

  const candidate = page.getByLabel('室内布局候选摘要', { exact: true })
  await expect(candidate).toBeVisible({ timeout: 60_000 })
  await expect(candidate.getByLabel('室内入口结果', { exact: true })).toContainText('主入口 · 活动室')
  await expect(candidate.getByLabel('室内入口结果', { exact: true })).toContainText('辅助入口 · 物资室')
  await expect(candidate).toContainText('1 组完整桌椅')
  await expect(candidate).toContainText('3/3 条建议通路通过净空检查')
  await candidate.getByRole('button', { name: '保存为新工程', exact: true }).click()
  await keyboardWorkspaceSaved(page)
  const saved = await keyboardProjectBackup(page, info.outputPath('generated.sceneweave'))
  expect(saved.document.constraints.entranceOpeningIds).toHaveLength(2)
  expect(Object.keys(saved.document.notes)).toHaveLength(2)
  const wideDoor = Object.values(saved.document.openings).find(opening => opening.widthMm === 2400)!
  expect(wideDoor.presentation?.kind).toBe('double')

  const objects = await openSceneObjects(page, '结构')
  await objects.getByLabel('搜索场景对象', { exact: true }).fill(wideDoor.id)
  await objects.locator(`[data-entity-id="${wideDoor.id}"]`).click()
  await page.getByLabel('门扇表现', { exact: true }).selectOption('frame')
  await page.getByRole('button', { name: '预览门窗修改', exact: true }).click()
  await page.getByLabel('确认完整影响范围', { exact: true }).check()
  await page.getByRole('button', { name: '采用结构修改', exact: true }).click()
  await keyboardWorkspaceSaved(page)
  const edited = await keyboardProjectBackup(page, info.outputPath('door-edited.sceneweave'))
  expect(edited.document.openings[wideDoor.id]).toEqual({ ...wideDoor, presentation: { kind: 'frame' } })
  expect(errors).toEqual([])
})
