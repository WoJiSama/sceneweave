import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

async function openStudy(page: Page) {
  await page.goto('/#assets')
  await page.locator('.asset-study-card').click()
  await page.getByRole('button', { name: '保存并打开副本', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: '书房与露台 · 墨绘原野', exact: true })).toBeVisible()
  await saved(page)
  await expect(page.getByLabel('材质场景主持人预览')).toBeVisible()
}
async function saved(page: Page) { await expect(page.locator('.asset-save')).toHaveText('本地已保存') }
async function number(page: Page, label: string, value: string) {
  const input = page.getByRole('spinbutton', { name: label, exact: true })
  await input.fill(value); await input.press('Tab')
}
async function scene(page: Page) { return page.evaluate(() => structuredClone(Reflect.get(window, '__sceneweaveAssetsDev').workspace.getState().project.document)) }
async function tab(page: Page, name: string) { await page.getByRole('group', { name: '场景对象分类' }).getByRole('button', { name, exact: true }).click() }
async function select(page: Page, id: string) { await page.locator(`[data-entity-id="${id}"]`).click() }
async function undo(page: Page) { await page.getByRole('button', { name: '撤销素材编辑', exact: true }).click() }

test('VIS-01 structure candidates cancel atomically, follow attached windows, and preserve material scale', async ({ page }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await openStudy(page)
  const baseline = await scene(page)
  await tab(page, '结构'); await select(page, 'study-v1')
  await number(page, '顶点 X', '7800')
  await expect(page.getByRole('button', { name: '采用结构修改' })).toBeVisible()
  expect(await scene(page)).toEqual(baseline)
  await page.getByRole('button', { name: '取消结构预览' }).click()
  await expect(page.getByRole('spinbutton', { name: '顶点 X', exact: true })).toHaveValue('8000')
  expect(await scene(page)).toEqual(baseline)
  await number(page, '顶点 X', '7800'); await page.getByRole('button', { name: '采用结构修改' }).click()
  expect((await scene(page)).vertices['study-v1'].xMm).toBe(7800)
  await undo(page)
  expect((await scene(page)).vertices).toEqual(baseline.vertices)
  const revisionBeforeInvalid = (await scene(page)).revision
  await number(page, '顶点 X', '100000')
  await expect(page.getByRole('alert')).toContainText('候选未通过')
  await expect(page.getByRole('button', { name: '采用结构修改' })).toHaveCount(0)
  expect((await scene(page)).revision).toBe(revisionBeforeInvalid)
  await select(page, 'study-w1'); await number(page, '墙体厚度', '300')
  await page.getByRole('button', { name: '采用结构修改' }).click()
  expect((await scene(page)).walls['study-w1'].thicknessMm).toBe(300)
  await undo(page)
  await page.getByRole('button', { name: '预览反转墙端点' }).click()
  await page.getByRole('button', { name: '采用结构修改' }).click()
  const reversed = await scene(page)
  expect(reversed.walls['study-w1'].startVertexId).toBe('study-v2')
  expect(reversed.openings['diagonal-window']).toEqual(baseline.openings['diagonal-window'])
  await undo(page)
  await select(page, 'terrace-v1'); await number(page, '轮廓点 X', '13500')
  await page.getByRole('button', { name: '采用结构修改' }).click()
  expect((await scene(page)).terrainAreas['terrace-area'].boundaryMm[1].positionMm.x).toBe(13500)
  await undo(page)
  await select(page, 'study-room'); await number(page, '木纹方向', '90')
  const worn = Object.values(baseline.materials).find((material: any) => material.catalogId === 'material.sw.wood-worn') as any
  await page.getByLabel('地面材质', { exact: true }).selectOption(worn.id)
  const edited = await scene(page)
  expect(edited.rooms['study-room'].floorStyle.base).toEqual({ ...baseline.rooms['study-room'].floorStyle.base, rotationDeg: 90, materialRef: { id: worn.id, version: 1 } })
  expect(edited.vertices).toEqual(baseline.vertices); expect(edited.walls).toEqual(baseline.walls)
  expect(edited.openings).toEqual(baseline.openings); expect(edited.props).toEqual(baseline.props)
  await saved(page); await page.reload(); await saved(page)
  expect(await scene(page)).toEqual(edited)
  await testInfo.attach('structure-material-workflow.json', { body: JSON.stringify({ cancelledUnchanged: true, illegalUnchanged: true, adoptedThenUndo: ['vertex', 'wallThickness', 'reverseWall', 'terracePoint'], stableOpening: reversed.openings['diagonal-window'], finalPaint: edited.rooms['study-room'].floorStyle.base, revision: edited.revision }, null, 2), contentType: 'application/json' })
  expect(errors).toEqual([])
})

test('VIS-01 groups retain expanded members through move, rotate, appearance swap, unpack, history and reload', async ({ page }, testInfo) => {
  await openStudy(page)
  const initial = await scene(page)
  await tab(page, '组合'); await select(page, 'study-group')
  await number(page, '组合 X', '3500')
  let current = await scene(page)
  for (const member of Object.values(initial.prefabInstances['study-group'].members) as any[]) {
    expect(current.props[member.propId].positionMm).toEqual({ x: initial.props[member.propId].positionMm.x + 500, y: initial.props[member.propId].positionMm.y })
  }
  await number(page, '组合旋转', '90')
  current = await scene(page)
  expect(current.props['study-chair'].positionMm).toEqual({ x: 2600, y: 2500 })
  expect(current.props['study-chair'].rotationDeg).toBe(90)
  await undo(page)
  expect((await scene(page)).prefabInstances['study-group'].rotationDeg).toBe(0)
  await tab(page, '物件'); await select(page, 'study-books-left')
  await number(page, '物件 X', '3150')
  expect((await scene(page)).prefabInstances['study-group'].members['books-left'].overrideFields).toContain('positionMm')
  await select(page, 'study-chair')
  const chairBefore = (await scene(page)).props['study-chair']
  const worn = Object.values(initial.propDefinitions).find((definition: any) => definition.catalogId === 'prop.sw.chair-worn') as any
  await page.getByLabel('物件外观变体').selectOption(worn.id)
  const chairAfter = (await scene(page)).props['study-chair']
  expect(chairAfter).toEqual({ ...chairBefore, definitionRef: { id: worn.id, version: 1 }, appearance: worn.defaultAppearance })
  await page.getByRole('button', { name: '选择整个书桌六件组', exact: true }).click()
  const beforeUnpack = await scene(page)
  await page.getByRole('button', { name: '拆开组合', exact: true }).click()
  let unpacked = await scene(page)
  expect(unpacked.prefabInstances['study-group']).toBeUndefined(); expect(unpacked.props).toEqual(beforeUnpack.props)
  await undo(page); expect((await scene(page)).prefabInstances).toEqual(beforeUnpack.prefabInstances)
  await page.getByRole('button', { name: '重做素材编辑', exact: true }).click()
  await saved(page); unpacked = await scene(page)
  await page.reload(); await saved(page)
  expect(await scene(page)).toEqual(unpacked)
  await testInfo.attach('prefab-workflow.json', { body: JSON.stringify({ movedMemberCount: 6, rotatedChair: { x: 2600, y: 2500 }, localOverrideRetained: true, appearanceOnly: true, unpackedStableIds: Object.keys(unpacked.props), undoRestoresGroup: true, reloadExact: true }, null, 2), contentType: 'application/json' })
})

test('VIS-01 blocks doorway-obstructing prop and group edits without consuming history or saving', async ({ page }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await openStudy(page)
  await select(page, 'terrace-chair-south')
  await number(page, '物件 Y', '4700'); await saved(page)
  const before = await scene(page)
  await number(page, '物件 X', '9900')
  await expect(page.getByRole('alert')).toContainText('terrace-door')
  await expect(page.getByRole('alert')).toContainText('terrace-chair-south')
  expect(await scene(page)).toEqual(before)
  await undo(page); await saved(page)
  const baseline = await scene(page)
  await expect(page.getByRole('button', { name: '重做素材编辑', exact: true })).toBeEnabled()
  await tab(page, '组合'); await select(page, 'terrace-group')
  await number(page, '组合 X', '10000')
  await expect(page.getByRole('alert')).toContainText('被阻挡')
  expect(await scene(page)).toEqual(baseline)
  await expect(page.getByRole('button', { name: '撤销素材编辑', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '重做素材编辑', exact: true })).toBeEnabled()
  const persisted = await page.evaluate(async () => {
    const dev = Reflect.get(window, '__sceneweaveAssetsDev')
    await dev.workspace.flush()
    return (await dev.repository.load(dev.workspace.getState().project.document.sceneId)).document
  })
  expect(persisted).toEqual(baseline)
  expect(errors).toEqual([])
  await testInfo.attach('doorway-edit-rejection.json', { body: JSON.stringify({ propEditRejected: true, groupEditRejected: true, revisionUnchangedOnFailure: true, historyRetained: true, savedDocumentUnchanged: true, entranceWidthMm: 1000, terraceWidthMm: 1200, approachDepthEachSideMm: [1000, 1500] }, null, 2), contentType: 'application/json' })
})

test('VIS-01 UI exports both 4K audiences and reopens complete project with no old cache or asset network', async ({ page, browser }, testInfo) => {
  test.setTimeout(90_000)
  await openStudy(page)
  const original = await scene(page)
  await page.screenshot({ path: testInfo.outputPath('vis01-workbench.png'), fullPage: true })
  await testInfo.attach('vis01-workbench.png', { path: testInfo.outputPath('vis01-workbench.png'), contentType: 'image/png' })
  const packageEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: '完整工程', exact: true }).click()
  const packageBytes = await readFile((await (await packageEvent).path())!)
  await testInfo.attach('vis01-complete.sceneweave', { body: packageBytes, contentType: 'application/zip' })
  for (const audience of ['gm', 'player'] as const) {
    if (audience === 'player') await page.getByRole('group', { name: '预览受众' }).getByRole('button', { name: '玩家', exact: true }).click()
    const canvas = page.getByLabel(audience === 'gm' ? '材质场景主持人预览' : '材质场景玩家预览')
    await expect(canvas).toBeVisible()
    const pngEvent = page.waitForEvent('download')
    await page.getByRole('button', { name: '4K PNG', exact: true }).click()
    const png = await pngEvent, pngBytes = await readFile((await png.path())!)
    expect(png.suggestedFilename()).toBe(`sceneweave-${audience}-map.png`)
    expect(pngBytes.readUInt32BE(16)).toBe(4096); expect(pngBytes.readUInt32BE(20)).toBe(2926)
    await testInfo.attach(`vis01-${audience}-4k.png`, { body: pngBytes, contentType: 'image/png' })
    await expect(page.getByRole('alert')).toContainText('PNG 已生成')
  }
  const freshContext = await browser.newContext({ viewport: { width: 1512, height: 982 } })
  try {
    const fresh = await freshContext.newPage(); await fresh.goto('/#assets')
    await expect(fresh.getByTestId('asset-workbench')).toBeVisible()
    await freshContext.setOffline(true)
    await fresh.getByLabel('选择完整素材工程').setInputFiles({ name: 'portable.sceneweave', mimeType: 'application/zip', buffer: packageBytes })
    await fresh.getByRole('button', { name: '保存并打开副本' }).click()
    await expect(fresh.getByRole('dialog')).toHaveCount(0); await saved(fresh)
    await expect(fresh.getByLabel('材质场景主持人预览')).toBeVisible()
    const imported = await scene(fresh)
    expect(imported.sceneId).not.toBe(original.sceneId)
    for (const key of ['props', 'walls', 'openings', 'rooms', 'terrainAreas', 'prefabInstances', 'propDefinitions', 'assets', 'styleThemes']) expect(imported[key]).toEqual(original[key])
    await select(fresh, 'study-desk'); await number(fresh, '物件 X', '3200'); await saved(fresh)
    expect((await scene(fresh)).props['study-desk'].positionMm.x).toBe(3200)
    await testInfo.attach('complete-portability.json', { body: JSON.stringify({ packageBytes: packageBytes.length, independentContext: true, importedWithoutNetwork: true, sourceUnchanged: true, allEntityCollectionsRetained: true, continuedEdit: true, output: [4096, 2926], browser: await browser.version() }, null, 2), contentType: 'application/json' })
  } finally { await freshContext.close() }
  expect(await scene(page)).toEqual(original)
})
