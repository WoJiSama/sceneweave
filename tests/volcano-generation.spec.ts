import { expect, test } from '@playwright/test'

test('volcano preview keeps separate physics, invalidates changed parameters and saves a cold-open project', async ({ page }, info) => {
  test.setTimeout(180_000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#home')
  await page.getByTestId('workspace-home').getByRole('button', { name: '新建场景', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '新建空白场景', exact: true })
  await dialog.getByLabel('场景名称', { exact: true }).fill('D5原工程')
  await dialog.getByRole('button', { name: '创建空白场景', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.asset-save')).toHaveText('本地已保存', { timeout: 30000 })
  await page.getByRole('tab', { name: '工程', exact: true }).click()
  const panel = page.getByRole('region', { name: '火山生成', exact: true })
  await panel.getByLabel('火山工程名称', { exact: true }).fill('D5火山活动区')
  await panel.getByRole('button', { name: '预览火山', exact: true }).click()
  await expect(panel.getByLabel('火山候选摘要', { exact: true })).toBeVisible({ timeout: 30000 })
  await expect(panel.getByLabel('火山实际生成结果', { exact: true })).toContainText('2 处高差连接、2 条路线')
  await expect(panel.getByLabel('火山危险与外观设置', { exact: true })).toContainText('火口标记危险，允许移动，代价 ×2')
  await expect(page.locator('.asset-view-actions')).toContainText('40.000 m × 32.000 m')
  await expect(page.getByLabel('材质场景主持人预览', { exact: true })).toBeVisible()
  await expect(page.locator('.asset-busy')).toHaveCount(0, { timeout: 30000 })
  await page.screenshot({ path: info.outputPath('volcano-preview.png') })
  // A changed physical parameter and material invalidate the old witnessed preview.
  await panel.getByLabel('火口高百分比', { exact: true }).fill('36')
  await panel.getByLabel('流道宽米', { exact: true }).fill('1.2')
  await panel.getByLabel('熔岩外观', { exact: true }).selectOption('cold')
  await expect(panel.getByLabel('火山候选摘要', { exact: true })).toHaveCount(0)
  await panel.getByRole('button', { name: '预览火山', exact: true }).click()
  await expect(panel.getByLabel('火山候选摘要', { exact: true })).toBeVisible({ timeout: 30000 })
  await expect(panel.getByLabel('火山危险与外观设置', { exact: true })).toContainText('火口标记危险，允许移动，代价 ×2')
  await expect(panel.getByLabel('火山危险与外观设置', { exact: true })).toContainText('流道标记危险，阻挡移动，代价 ×3')
  await panel.getByRole('button', { name: '保存为新工程', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: '火山已完整保存并打开' })).toBeVisible({ timeout: 30000 })
  await expect(panel.getByLabel('火山候选摘要', { exact: true })).toHaveCount(0)
  await expect(page.locator('.asset-save')).toHaveText('本地已保存', { timeout: 30000 })
  await page.goto('/#home')
  await page.reload()
  const home = page.getByTestId('workspace-home')
  await expect(home.locator('.home-project-row').filter({ hasText: 'D5原工程' })).toHaveCount(1, { timeout: 30000 })
  const row = home.locator('.home-project-row').filter({ hasText: 'D5火山活动区' })
  await expect(row).toHaveCount(1)
  await row.getByRole('button', { name: '打开', exact: true }).click()
  await expect(page.getByLabel('材质场景主持人预览', { exact: true })).toBeVisible({ timeout: 30000 })
  await expect(page.locator('.asset-save')).toHaveText('本地已保存', { timeout: 30000 })
  await expect(page.locator('.asset-busy')).toHaveCount(0, { timeout: 30000 })
  await page.getByRole('tab', { name: '对象', exact: true }).click()
  await page.getByRole('group', { name: '场景对象分类', exact: true }).getByRole('button', { name: '结构', exact: true }).click()
  await expect(page.locator('.asset-entity-list button[data-entity-id]').filter({ hasText: '台阶连接' })).toHaveCount(2)
  await expect(page.locator('.asset-entity-list button[data-entity-id]').filter({ hasText: '0.5m' }).first()).toBeVisible()
  await page.screenshot({ path: info.outputPath('volcano-cold-open.png') })
  expect(errors).toEqual([])
})
