import { expect, test, type Locator, type Page } from '@playwright/test'
import { createKeyboardProject, keyboardProjectBackup, keyboardResourceHashes, keyboardWorkspaceSaved, openKeyboardPanel } from './keyboard-ux-helpers'
import { openWorkspaceModule } from './workspace-navigation-helpers'
import { openDetailsBySummary } from './workspace-ux-helpers'

async function inspectDoor(page: Page, id: string): Promise<Locator> {
  const scene = await openWorkspaceModule(page, '场景')
  const allLayers = scene.getByRole('button', { name: '显示所有图层的对象', exact: true })
  if (await allLayers.isVisible()) await allLayers.click()
  await scene.getByRole('group', { name: '场景对象分类', exact: true }).getByRole('button', { name: '结构', exact: true }).click()
  await scene.getByLabel('搜索场景对象', { exact: true }).fill(id)
  await scene.locator(`[data-entity-id="${id}"]`).click()
  return (await openKeyboardPanel(page, 'inspector')).getByLabel('建筑属性', { exact: true })
}

test('actual doorway starts the ordinary road draft with exact parameters, refuses an internal door and preserves cancel/adopt/undo', async ({ page, browser }, info) => {
  test.setTimeout(360_000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await createKeyboardProject(page, '从真实门口接路的普通页面旅程')
  await openWorkspaceModule(page, '素材与布景')
  const palette = page.getByRole('region', { name: '主题素材包', exact: true })
  await palette.locator(':scope > details > summary').click()
  await palette.getByLabel('选择主题包', { exact: true }).selectOption('wilderness')
  await palette.getByRole('button', { name: '加载所选主题包', exact: true }).click()
  await expect(palette).toContainText('已加载', { timeout: 90_000 })
  await palette.getByText('两份可编辑代表场景', { exact: true }).click()
  const sourcePath = info.outputPath('door-road-source.sceneweave'), downloaded = page.waitForEvent('download')
  await palette.getByRole('button', { name: /^下载场景 ·/ }).first().click()
  await (await downloaded).saveAs(sourcePath)
  const context = await browser.newContext()
  try {
    const target = await context.newPage(); target.on('pageerror', error => errors.push(error.message))
    await target.goto(new URL('./#home', page.url()).href)
    const choosing = target.waitForEvent('filechooser')
    await target.getByTestId('workspace-home').getByRole('button', { name: '打开工程文件', exact: true }).click()
    await (await choosing).setFiles(sourcePath)
    await keyboardWorkspaceSaved(target)
    const before = await keyboardProjectBackup(target, info.outputPath('door-road-before.sceneweave'))
    let inspector = await inspectDoor(target, 'watch-inner-door')
    await inspector.getByRole('button', { name: '从此门口接路', exact: true }).click()
    await expect(inspector.getByRole('alert')).toContainText('恰好附着一个实际房间')
    await expect(target.getByTestId('building-sketch')).toHaveCount(0)
    expect((await keyboardProjectBackup(target, info.outputPath('door-road-refused.sceneweave'))).hashes).toEqual(before.hashes)

    inspector = await inspectDoor(target, 'watch-entrance')
    const shortcutWidth = inspector.getByLabel('门前道路净宽', { exact: true })
    await shortcutWidth.fill('1'); await shortcutWidth.press('Tab')
    await inspector.getByRole('button', { name: '从此门口接路', exact: true }).click()
    const tools = target.getByTestId('workspace-inspector').locator('.outdoor-panel.workspace-tool-parameters')
    await expect(tools).toBeVisible()
    await expect(target.getByTestId('workspace-module-navigation').getByRole('button', { name: '地形', exact: true })).toHaveAttribute('aria-current', 'page')
    await expect(tools.getByLabel('室外通路净宽', { exact: true })).toHaveValue('1')
    await expect(tools.getByLabel('室外内容可见性', { exact: true })).toHaveValue('public')
    const support = before.document.rooms['watch-record-room'].supportRef
    await expect(tools.getByLabel('道路支撑表面', { exact: true })).toHaveValues([`${support.kind}:${support.id}`])
    await openDetailsBySummary(tools, /^精确坐标 · 道路中心线$/)
    const coordinates = tools.getByLabel('室外坐标', { exact: true }), anchor = { x: 6750, y: 12111 }
    await expect(coordinates).toHaveValue(`${anchor.x}, ${anchor.y}`)
    await expect(target.locator('.workspace-unified')).toHaveAttribute('data-revision', String(before.document.revision))
    await expect(target.getByRole('region', { name: '候选审阅', exact: true })).toHaveCount(0)
    await target.getByRole('group', { name: '地图视口', exact: true }).focus()
    await target.keyboard.press('Escape')
    await target.getByRole('button', { name: '取消室外草稿', exact: true }).click()
    expect((await keyboardProjectBackup(target, info.outputPath('door-road-cancelled.sceneweave'))).hashes).toEqual(before.hashes)

    inspector = await inspectDoor(target, 'watch-entrance')
    await inspector.getByLabel('门前道路净宽', { exact: true }).fill('1')
    await inspector.getByLabel('门前道路净宽', { exact: true }).press('Tab')
    await inspector.getByRole('button', { name: '从此门口接路', exact: true }).click()
    await openDetailsBySummary(tools, /^精确坐标 · 道路中心线$/)
    const end = { x: anchor.x, y: anchor.y + 2000 }
    await coordinates.fill(`${anchor.x}, ${anchor.y}\n${end.x}, ${end.y}`)
    await tools.getByRole('button', { name: '预览室外修改', exact: true }).click()
    const review = target.getByRole('region', { name: '候选审阅', exact: true })
    await review.getByLabel('确认完整影响范围', { exact: true }).check()
    await review.getByRole('button', { name: '采用室外修改', exact: true }).click()
    await expect(review).toHaveCount(0); await keyboardWorkspaceSaved(target)
    const adopted = await keyboardProjectBackup(target, info.outputPath('door-road-adopted.sceneweave'))
    const created = Object.values(adopted.document.paths).filter(path => !before.document.paths[path.id])
    expect(created).toHaveLength(1)
    expect(created[0]).toMatchObject({ floorId: before.document.openings['watch-entrance'].floorId, centerlineMm: [anchor, end], widthMm: 1000, supportRefs: [support], visibility: 'public' })
    expect(adopted.document.openings).toEqual(before.document.openings)
    expect(adopted.document.rooms).toEqual(before.document.rooms)
    expect(adopted.document.revision).toBe(before.document.revision + 1)
    expect(keyboardResourceHashes(adopted.hashes)).toEqual(keyboardResourceHashes(before.hashes))
    await target.getByRole('button', { name: '撤销编辑', exact: true }).click(); await keyboardWorkspaceSaved(target)
    const undone = await keyboardProjectBackup(target, info.outputPath('door-road-undone.sceneweave'))
    expect(undone.document).toEqual({ ...before.document, revision: before.document.revision + 2, updatedAt: undone.document.updatedAt })
    expect(keyboardResourceHashes(undone.hashes)).toEqual(keyboardResourceHashes(before.hashes))
    await target.screenshot({ path: info.outputPath('door-road-ordinary-tool.png'), animations: 'disabled' })
    expect(errors).toEqual([])
  } finally { await context.close() }
})
