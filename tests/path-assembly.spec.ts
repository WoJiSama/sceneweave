async function assertRenderedOpening(page: Page, info: TestInfo, name: string, bounds: BoundsMm, center: PointMm, closeGap: () => Promise<void>) {
  const canvas = page.getByLabel('材质场景主持人预览', { exact: true })
  const fraction = { x: (center.x - bounds.x) / bounds.width, y: (center.y - bounds.y) / bounds.height }
  const canvasPixel = () => canvas.evaluate((node: HTMLCanvasElement, at) => {
    const x = Math.floor(at.x * node.width), y = Math.floor(at.y * node.height)
    return [...node.getContext('2d')!.getImageData(x, y, 1, 1).data]
  }, fraction)
  const { PNG } = createRequire(import.meta.url)('../node_modules/playwright-core/lib/utilsBundle.js')
  const pngPixel = (bytes: Buffer): number[] => {
    const raster = PNG.sync.read(bytes)
    const x = Math.floor(fraction.x * raster.width), y = Math.floor(fraction.y * raster.height)
    const i = (y * raster.width + x) * 4
    return [...raster.data.subarray(i, i + 4)]
  }
  const visibleDifference = (first: number[], second: number[]) =>
    first.slice(0, 3).reduce((sum, value, i) => sum + Math.abs(value - second[i]), 0)
  const openCanvas = await canvasPixel()
  await canvas.screenshot({ path: info.outputPath(`${name}-canvas.png`) })
  await png(page, info, 'gm', name)
  const player = await png(page, info, 'player', name)
  // Change only the presence of the gap to compare the same world point against a solid span.
  await closeGap()
  expect(visibleDifference(openCanvas, await canvasPixel())).toBeGreaterThan(30)
  const closed = await png(page, info, 'player', `${name}-gap-closed`)
  expect(visibleDifference(pngPixel(player), pngPixel(closed))).toBeGreaterThan(30)
  await replayEdit(page, '撤销编辑')
  expect(await canvasPixel()).toEqual(openCanvas)
  return player
}

