async function worldClick(page: Page, point: PointMm, extent: { width: number; height: number }) {
  const canvas = page.locator('canvas[aria-label="材质场景主持人预览"]')
  const box = await canvas.boundingBox()
  if (!box) throw new Error('Missing visible map')
  await page.mouse.click(box.x + box.width * point.x / extent.width, box.y + box.height * point.y / extent.height)
}

async function adoptChange(page: Page, kind: '室外' | '视觉' = '室外') {
  await page.getByRole('checkbox', { name: '确认完整影响范围', exact: true }).check()
  await page.getByRole('button', { name: '采用' + kind + '修改', exact: true }).click()
  await keyboardWorkspaceSaved(page)
}

async function png(page: Page, info: TestInfo, audience: 'gm' | 'player', name = 'bridges') {
  const destination = info.outputPath(`${name}-${audience}.png`)
  const button = await mapExportButton(page, audience), pending = page.waitForEvent('download')
  await button.click()
  await (await pending).saveAs(destination)
  await keyboardWorkspaceSaved(page)
  const data = await readFile(destination)
  expect([...data.subarray(0, 8)]).toEqual([137, 80, 78, 71, 13, 10, 26, 10])
  expect(Math.max(data.readUInt32BE(16), data.readUInt32BE(20))).toBe(4096)
  await page.locator('details.workspace-export-menu > summary').click()
  return data
}

