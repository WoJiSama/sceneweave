// Current normal production UI only; engineering facts come from downloaded backups.
import { closeWorkspaceDrawers, openBuildingTask, openOutdoorTask } from './workspace-navigation-helpers'
import { expect, test, type Page, type TestInfo } from '@playwright/test'
import { writeFile } from 'node:fs/promises'
import { createKeyboardProject, keyboardProjectBackup, keyboardWorkspaceSaved, openKeyboardPanel, clickKeyboardWorldPoint } from './keyboard-ux-helpers'
import { openExportMenu, openNewScene } from './workspace-ux-helpers'

test.use({ actionTimeout: 15000 })
async function closeDrawers(page: Page) {
  await closeWorkspaceDrawers(page)
}
async function shot(page: Page, info: TestInfo, name: string) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.screenshot({ path: info.outputPath(`${name}.png`), animations: 'disabled' })
}
const longName = '长名称场景与房间的可读性检查'.repeat(10)
for (const width of [1512, 390]) test(`candidate feedback, dialogs and canvas cues at ${width}px`, async ({ page, browser }, info) => {
  test.setTimeout(180000)
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.setViewportSize({ width, height: width === 390 ? 844 : 982 })
  await createKeyboardProject(page, `反馈与弹窗 ${width}`)
  const before = await keyboardProjectBackup(page, info.outputPath('before.sceneweave'))
  const building = await openBuildingTask(page)
  await building.getByLabel('房间名称', { exact: true }).fill(longName)
  await building.getByRole('button', { name: '预览新房间', exact: true }).click()
  const candidate = page.getByRole('region', { name: '候选审阅', exact: true })
  await expect(candidate).toBeVisible()
  const adopt = candidate.getByRole('button', { name: '采用结构修改', exact: true })
  await expect(adopt).toBeDisabled()
  await shot(page, info, '01-long-candidate')
  const body = candidate.locator('.workspace-candidate-body')
  expect(await body.locator('.composition-preview-details').evaluate(n => getComputedStyle(n).maxHeight)).toBe('none')
  await body.evaluate(n => n.scrollTo(0, n.scrollHeight))
  const actions = candidate.locator('.workspace-candidate-actions')
  const box = await actions.boundingBox()
  expect(box!.y).toBeGreaterThanOrEqual(0)
  expect(box!.y + box!.height).toBeLessThanOrEqual(page.viewportSize()!.height)
  await candidate.getByLabel('确认完整影响范围', { exact: true }).check()
  await expect(adopt).toBeEnabled()
  await shot(page, info, '02-candidate-actions')
  await candidate.getByRole('button', { name: '取消结构预览', exact: true }).click()
  await keyboardWorkspaceSaved(page)
  await openKeyboardPanel(page, 'resources')
  if (await page.getByRole('button', { name: '取消建筑草稿', exact: true }).isVisible()) await page.getByRole('button', { name: '取消建筑草稿', exact: true }).click()
  const outdoor = await openOutdoorTask(page)
  const coords = outdoor.locator('.outdoor-coordinates details')
  await coords.locator('summary').click(); await outdoor.getByLabel('室外坐标', { exact: true }).fill('坏坐标'.repeat(30)); await coords.locator('summary').click()
  await outdoor.getByRole('button', { name: '预览室外修改', exact: true }).click()
  await expect(outdoor.getByRole('alert')).toBeVisible(); await shot(page, info, '03-form-error')
  await closeDrawers(page)
  await page.getByRole('button', { name: '取消室外草稿', exact: true }).click()
  await page.getByRole('button', { name: '工具：画房间', exact: true }).click()
  await closeDrawers(page)
  const hint = page.getByRole('status', { name: '房间绘制提示', exact: true })
  await expect(hint).toContainText('0 / 2 点')
  await clickKeyboardWorldPoint(page, { x: 2000, y: 2000 }, before.document.exportBoundsMm)
  await expect(hint).toContainText('1 / 2 点')
  await shot(page, info, '04-drawing-one-point')
  await hint.getByRole('button', { name: '退出房间绘制', exact: true }).click()
  await expect(hint).toHaveCount(0)
  await expect(page.getByRole('button', { name: '工具：画房间', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await expect(candidate).toHaveCount(0)
  // Leaving canvas point entry keeps its form draft until explicitly cancelled.
  await page.getByRole('button', { name: '取消建筑草稿', exact: true }).click()
  await keyboardWorkspaceSaved(page)
  await page.getByRole('button', { name: '工具：画地形', exact: true }).click(); await closeDrawers(page)
  const outdoorHint = page.getByRole('status', { name: '地形绘制提示', exact: true })
  await expect(outdoorHint).toContainText('道路与连接至少两点')
  await outdoorHint.getByRole('button', { name: '退出地形绘制', exact: true }).click()
  await expect(outdoorHint).toHaveCount(0)
  await page.getByRole('button', { name: '取消室外草稿', exact: true }).click()
  await keyboardWorkspaceSaved(page)
  const dialog = await openNewScene(page)
  await dialog.getByLabel('场景名称', { exact: true }).fill(longName)
  await dialog.getByLabel('画布宽度', { exact: true }).fill('999')
  await dialog.getByRole('button', { name: '创建空白场景', exact: true }).click()
  await expect(dialog.getByRole('alert')).toBeVisible()
  await shot(page, info, '05-new-dialog-error')
  if (width === 390) {
    await page.setViewportSize({ width, height: 600 })
    await dialog.getByLabel('画布高度', { exact: true }).focus()
    const field = await dialog.getByLabel('画布高度', { exact: true }).boundingBox(), footer = await dialog.locator('.modal-actions').boundingBox()
    expect(field!.y + field!.height).toBeLessThanOrEqual(footer!.y)
    await shot(page, info, '05-short-dialog-focus')
    await page.setViewportSize({ width, height: 844 })
  }
  const titleStyle = await dialog.getByRole('heading').evaluate(n => ({ size: getComputedStyle(n).fontSize, font: getComputedStyle(n).fontFamily }))
  expect(titleStyle.size).toBe('16px')
  await dialog.getByRole('button', { name: '取消', exact: true }).focus(); await page.keyboard.press('Enter')
  await expect(dialog).toHaveCount(0)
  await closeDrawers(page); await openExportMenu(page)
  await page.getByRole('button', { name: 'VTT 导出', exact: true }).click()
  const vtt = page.getByRole('dialog', { name: 'VTT 导出预检', exact: true })
  await expect(vtt).toBeVisible()
  for (const state of [{ isComposing: true }, { keyCode: 229 }]) {
    await vtt.dispatchEvent('keydown', { key: 'Escape', code: 'Escape', bubbles: true, ...state })
    await expect(vtt).toBeVisible()
  }
  if (width === 390) {
    await page.setViewportSize({ width, height: 600 })
    const checkbox = vtt.getByRole('checkbox')
    await checkbox.focus(); await page.keyboard.press('Space')
    await expect(vtt.getByRole('button', { name: '下载 VTT 导入包', exact: true })).toBeEnabled()
    const field = await checkbox.boundingBox(), footer = await vtt.locator('.modal-actions').boundingBox()
    expect(field!.y + field!.height).toBeLessThanOrEqual(footer!.y)
    await shot(page, info, '06-short-vtt-focus')
    await page.setViewportSize({ width, height: 844 })
  }
  await shot(page, info, '06-vtt-dialog')
  await vtt.getByRole('button', { name: '关闭', exact: true }).press('Escape')
  await expect(vtt).toHaveCount(0)
  const menu = page.locator('.workspace-export-menu')
  await expect(menu.getByRole('button', { name: 'VTT 导出', exact: true })).toBeFocused()
  await page.keyboard.press('Escape'); await expect(menu).not.toHaveAttribute('open')
  await expect(menu.locator('summary')).toBeFocused()
  const after = await keyboardProjectBackup(page, info.outputPath('after.sceneweave'))
  expect(after.hashes).toEqual(before.hashes)
  await page.getByRole('button', { name: '回到首页', exact: true }).click()
  await page.getByLabel('搜索最近工程', { exact: true }).fill('没有这样的工程名'.repeat(10))
  await expect(page.getByText('没有匹配的工程', { exact: true })).toBeVisible()
  await shot(page, info, '07-home-no-match')
  await page.getByRole('button', { name: '清空工程搜索', exact: true }).click()
  await expect(page.getByLabel('搜索最近工程', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('搜索最近工程', { exact: true })).toBeFocused()
  await expect(page.getByTestId('workspace-home').locator(`[data-project-key="native:${before.document.sceneId}"]`)).toBeVisible()
  expect(errors).toEqual([])
  await writeFile(info.outputPath('feedback-facts.json'), JSON.stringify({ width, browser: browser.version(), errors, titleStyle, cancelledArchiveEntries: Object.keys(before.hashes).length, unchanged: true, nativeIme: 'not run by user decision; composition handler only', candidateActionsReachable: true, drawingCueAndExit: true }, null, 2))
})
