import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { unzipSync } from 'fflate'
import { referenceTerrainPixels } from '../src/shared/generation/map-reference.test-fixture'
import { encodeCanonicalPng } from '../src/shared/project/png-rgba'
import { checkGradedRoadOnValidScene } from '../src/shared/geometry/terrain-travel'
import { createKeyboardProject, keyboardProjectBackup, keyboardResourceHashes, keyboardWorkspaceSaved } from './keyboard-ux-helpers'
import { openGenerationTask, openSceneObjects } from './workspace-navigation-helpers'

test('页面从参考图取样，检查低处登顶后保存真实可编辑工程', async ({ page }, info) => {
  test.setTimeout(180_000)
  await createKeyboardProject(page, '原始地图', { widthMeters: 24, heightMeters: 18 })
  await openGenerationTask(page, '参考图地形')
  const dialog = page.getByRole('dialog', { name: '参考图地形', exact: true })
  const { data, width, height } = referenceTerrainPixels()
  const png = encodeCanonicalPng({ width, height, rgba: data })
  await dialog.getByLabel('参考图片').setInputFiles({ name: 'inlet.png', mimeType: 'image/png', buffer: Buffer.from(png) })
  await dialog.getByLabel('地图名称').fill('沿湾高地')
  await dialog.getByText('用像素坐标取点', { exact: true }).click()
  const mark = async (x: number, y: number) => {
    await dialog.getByLabel('X 像素').fill(String(x))
    await dialog.getByLabel('Y 像素').fill(String(y))
    await dialog.getByRole('button', { name: '添加取点', exact: true }).click()
  }
  await mark(151, 30)
  await mark(44, 77)
  await dialog.getByRole('button', { name: '提取轮廓', exact: true }).click()
  await expect(dialog.getByText('2 块陆地，1 处内水')).toBeVisible()
  await dialog.getByRole('button', { name: '补陆地', exact: true }).click()
  await mark(122, 22)
  await expect(dialog.getByText('有修正待应用')).toBeVisible()
  await dialog.getByRole('button', { name: '撤回最后一笔', exact: true }).click()
  await dialog.getByRole('button', { name: '提取轮廓', exact: true }).click()
  await expect(dialog.getByText('2 块陆地，1 处内水')).toBeVisible()
  await dialog.getByRole('button', { name: '标定比例', exact: true }).click()
  await mark(10, 20)
  await mark(110, 20)
  await dialog.getByLabel('标尺实距（米）').fill('47.5')
  await dialog.getByRole('button', { name: '标地貌', exact: true }).click()
  await dialog.getByLabel('范围半径（原图长边 %）').fill('12')
  await dialog.getByLabel('纵向半径（原图长边 %）').fill('9')
  await dialog.getByLabel('旋转角度（度）').fill('22')
  await mark(92, 31)
  await dialog.getByRole('button', { name: '标低处出发区', exact: true }).click()
  await dialog.getByLabel('绕行方向').selectOption('north')
  await dialog.getByLabel('最小高差（米）').fill('50')
  await mark(45, 47)
  const diagnosis = dialog.getByRole('region', { name: '几何诊断' })
  const preview = dialog.getByRole('button', { name: '生成地图预览', exact: true })
  const view = dialog.getByAltText('生成地图的正俯视预览')
  const adopt = dialog.getByRole('button', { name: '打开为新工程', exact: true })
  await preview.click()
  await expect(diagnosis).toContainText('需要调整几何或通路', { timeout: 30_000 })
  await expect(view).toBeVisible({ timeout: 45_000 })
  await expect(adopt).toBeDisabled()
  await dialog.getByRole('button', { name: '调整路线', exact: true }).click()
  await dialog.getByLabel('最小高差（米）').fill('1.2')
  await dialog.getByRole('button', { name: '应用到原位置', exact: true }).click()
  await dialog.getByRole('button', { name: '只检查几何', exact: true }).click()
  await expect(diagnosis).toContainText('所需几何与通路通过', { timeout: 30_000 })
  await expect(diagnosis).toContainText('到地标 6 米')
  await preview.click()
  await expect(view).toBeVisible({ timeout: 45_000 })
  const originalPreview = await view.getAttribute('src')
  await dialog.getByRole('combobox', { name: '画风', exact: true }).selectOption('handDrawn')
  await expect(view).not.toHaveAttribute('src', originalPreview!, { timeout: 45_000 })
  await expect(diagnosis).toContainText('所需几何与通路通过')
  await dialog.getByRole('button', { name: '斜俯视', exact: true }).click()
  await expect(dialog.getByAltText('生成地图的斜俯视预览')).toBeVisible({ timeout: 45_000 })
  await adopt.click()
  await page.getByRole('button', { name: '保存并打开副本', exact: true }).click()
  await keyboardWorkspaceSaved(page)
  const archive = info.outputPath('reference.sceneweave')
  const { document, hashes } = await keyboardProjectBackup(page, archive)
  expect(document.title).toBe('沿湾高地')
  expect(document.artStyle?.active).toBe('handDrawn')
  expect(document.exportBoundsMm.width).toBe(76000)
  const manifest = unzipSync(new Uint8Array(await readFile(archive)))['manifest.json']
  expect(JSON.parse(new TextDecoder().decode(manifest)).minReaderVersion).toBe(3)
  expect(document.terrainAreas.main.reliefFinish).toBe('weathered-v2')
  expect(document.terrainAreas['main-lake-1'].blocksMovement).toBe(true)
  const [road] = Object.values(document.paths)
  const profile = checkGradedRoadOnValidScene(document, road)
  expect(profile.ok).toBe(true)
  expect(profile.treadCount).toBeGreaterThan(0)
  expect(profile.elevationsMm[1] - profile.elevationsMm[0]).toBeGreaterThan(4000)

  const navigation = await openSceneObjects(page, '结构')
  const allLayers = navigation.getByRole('button', { name: '显示所有图层的对象', exact: true })
  if (await allLayers.isVisible()) await allLayers.click()
  await navigation.getByLabel('搜索场景对象', { exact: true }).fill('main')
  await navigation.locator('[data-entity-id="main"]').click()
  const inspector = page.getByTestId('workspace-inspector')
  const reliefFinish = inspector.getByRole('combobox', { name: '坡面岩纹', exact: true })
  await expect(reliefFinish).toHaveValue('weathered-v2', { timeout: 15000 })
  await reliefFinish.selectOption('')
  await inspector.getByRole('button', { name: '预览坡面岩纹', exact: true }).click()
  const review = page.getByRole('region', { name: '候选审阅', exact: true })
  await review.getByLabel('确认完整影响范围', { exact: true }).check()
  await review.getByRole('button', { name: '采用室外修改', exact: true }).click()
  await keyboardWorkspaceSaved(page)
  await page.reload()
  await page.getByRole('button', { name: '回到首页', exact: true }).click()
  await page.getByTestId('workspace-home').locator('.home-project-row').filter({ hasText: document.title })
    .getByRole('button', { name: '打开', exact: true }).click()
  await keyboardWorkspaceSaved(page)
  const reopened = await keyboardProjectBackup(page, info.outputPath('reference-reopened.sceneweave'))
  const { reliefFinish: _finish, ...area } = document.terrainAreas.main
  expect(reopened.document.terrainAreas.main).toEqual(area)
  expect(reopened.document.paths).toEqual(document.paths)
  expect(keyboardResourceHashes(reopened.hashes)).toEqual(keyboardResourceHashes(hashes))
})
