import { openGenerationTask, openGenerationSettings, openTerrainTask } from './workspace-navigation-helpers'
import { expect, test } from '@playwright/test'

test('local crater adjustment previews full writes, adopts once, undoes, redoes and cold opens', async ({ page }, info) => {
  test.setTimeout(180_000)
  const errors: string[] = []
  const workers: string[] = [], generationRequests: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('worker', worker => workers.push(worker.url()))
  page.on('request', request => { if (/\/v1\/(?:generation|tasks)/.test(request.url())) generationRequests.push(request.url()) })
  await page.goto('/#home')
  await page.getByTestId('workspace-home').getByRole('button', { name: '新建场景', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '新建空白场景', exact: true })
  await dialog.getByLabel('场景名称', { exact: true }).fill('D6起始工程')
  await dialog.getByRole('button', { name: '创建空白场景', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.asset-save')).toHaveText('本地已保存', { timeout: 30000 })
  await openGenerationTask(page, '火山')
  await openGenerationSettings(page)
  await expect(page.getByLabel('参数地图生成位置', { exact: true })).toHaveValue('worker')
  const volcano = page.getByRole('region', { name: '火山生成', exact: true })
  const volcanoCandidate = page.getByTestId('workspace-inspector').getByLabel('火山候选摘要', { exact: true })
  await volcano.getByLabel('火山工程名称', { exact: true }).fill('D6局部火山')
  await volcano.getByRole('button', { name: '预览火山', exact: true }).click()
  await expect(volcanoCandidate).toBeVisible({ timeout: 30000 })
  expect(workers.some(url => /worker-.*\.js/.test(url) || /generation\/worker\.ts/.test(url))).toBe(true)
  await volcanoCandidate.getByRole('button', { name: '保存为新工程', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: '火山已完整保存并打开' })).toBeVisible({ timeout: 30000 })
  await openTerrainTask(page, '局部重生成')
  const local = page.getByRole('region', { name: '受限局部重生成', exact: true })
  const candidate = page.getByTestId('workspace-inspector').getByLabel('局部重生成候选摘要', { exact: true })
  await expect(local).toBeVisible()
  const before = await local.getByLabel('火口当前轮廓坐标', { exact: true }).inputValue()
  await local.getByLabel('火口右侧扩展米', { exact: true }).fill('0.5')
  const after = await local.getByLabel('火口调整后轮廓坐标', { exact: true }).inputValue()
  expect(after).not.toBe(before)
  await local.getByRole('button', { name: '预览局部重生成', exact: true }).click()
  await expect(candidate).toBeVisible({ timeout: 30000 })
  await openTerrainTask(page, '局部重生成')
  await expect(local.getByLabel('火口当前轮廓坐标', { exact: true })).toHaveValue(before)
  // Editing a parameter revokes the previous candidate; a fresh preview is required.
  await local.getByLabel('火口右侧扩展米', { exact: true }).fill('0.6')
  await expect(candidate).toHaveCount(0)
  await local.getByLabel('火口右侧扩展米', { exact: true }).fill('0.5')
  await local.getByRole('button', { name: '预览局部重生成', exact: true }).click()
  await expect(candidate).toBeVisible({ timeout: 30000 })
  await expect(candidate).toContainText('terrainAreas')
  await candidate.getByText('只读依赖', { exact: true }).click()
  await expect(candidate.getByLabel('局部生成只读依赖', { exact: true })).not.toHaveValue('')
  await candidate.getByRole('button', { name: '保护并采用局部修改', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: '采用局部重生成' })).toBeVisible({ timeout: 30000 })
  await openTerrainTask(page, '局部重生成')
  await expect(local.getByLabel('火口当前轮廓坐标', { exact: true })).toHaveValue(after)
  await expect(page.locator('.asset-save')).toHaveText('本地已保存', { timeout: 30000 })
  await page.getByRole('button', { name: '撤销编辑', exact: true }).click()
  await expect(local.getByLabel('火口当前轮廓坐标', { exact: true })).toHaveValue(before)
  await expect(page.locator('.asset-save')).toHaveText('本地已保存', { timeout: 30000 })
  await page.getByRole('button', { name: '重做编辑', exact: true }).click()
  await expect(local.getByLabel('火口当前轮廓坐标', { exact: true })).toHaveValue(after)
  await expect(page.locator('.asset-save')).toHaveText('本地已保存', { timeout: 30000 })
  await page.goto('/#home')
  await page.reload()
  const row = page.getByTestId('workspace-home').locator('.home-project-row').filter({ hasText: 'D6局部火山' })
  await expect(row).toHaveCount(1, { timeout: 30000 })
  await row.getByRole('button', { name: '打开', exact: true }).click()
  await expect(page.getByLabel('材质场景主持人预览', { exact: true })).toBeVisible({ timeout: 30000 })
  await openTerrainTask(page, '局部重生成')
  await expect(local.getByLabel('火口当前轮廓坐标', { exact: true })).toHaveValue(after)
  await expect(page.locator('.asset-save')).toHaveText('本地已保存', { timeout: 30000 })
  await page.screenshot({ path: info.outputPath('local-crater-cold-open.png') })
  expect(errors).toEqual([])
  expect(generationRequests).toEqual([])
})
