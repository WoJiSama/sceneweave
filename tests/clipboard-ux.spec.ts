import { expect, test } from '@playwright/test'
import { createKeyboardProject, keyboardProjectBackup, keyboardResourceHashes, keyboardWorkspaceSaved, openKeyboardPanel, placeKeyboardLamp, selectKeyboardProp } from './keyboard-ux-helpers'
import { reloadSaved } from './workspace-ux-helpers'

test('production keyboard clipboard keeps object data private, previews once and rejects changed or reopened sources', async ({ page }, info) => {
  test.setTimeout(180000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await createKeyboardProject(page, '剪贴板保密工程名称')
  await placeKeyboardLamp(page)
  const placed = await keyboardProjectBackup(page, info.outputPath('clipboard-placed.sceneweave'))
  const [placedSource] = Object.values(placed.document.props)
  expect(Object.keys(placed.document.props)).toHaveLength(1)
  await selectKeyboardProp(page, placedSource.id)
  await page.getByLabel('物件旋转', { exact: true }).fill('15')
  await page.getByLabel('物件旋转', { exact: true }).press('Tab')
  await keyboardWorkspaceSaved(page)
  const original = await keyboardProjectBackup(page, info.outputPath('clipboard-original.sceneweave'))
  const source = original.document.props[placedSource.id]
  expect(source).toMatchObject({ positionMm: { x: 4000, y: 4000 }, rotationDeg: 15 })
  const viewport = page.getByRole('group', { name: '地图视口', exact: true })
  const review = page.getByRole('region', { name: '候选审阅', exact: true })
  const revision = page.locator('.workspace-unified')
  const copy = async () => {
    await viewport.focus()
    await viewport.press('ControlOrMeta+C')
    await expect(page.locator('.asset-notice')).toContainText('已复制 1 个独立物件')
  }
  const paste = async () => {
    await viewport.focus()
    await viewport.press('ControlOrMeta+V')
    await expect(review).toContainText('粘贴所选 · 1 个独立物件')
    await expect(review.getByRole('button', { name: '采用批量修改', exact: true })).toHaveCount(1)
    await expect(review.getByRole('button', { name: '采用批量修改', exact: true })).toBeEnabled()
    await keyboardWorkspaceSaved(page)
  }

  // These are native browser keyboard copy/paste events, never injected ClipboardEvents.
  await copy()
  await expect(revision).toHaveAttribute('data-revision', String(original.document.revision))
  await expect(review).toHaveCount(0)
  const navigation = await openKeyboardPanel(page, 'navigation')
  const search = navigation.getByLabel('搜索场景对象', { exact: true })
  await search.fill('')
  await search.press('ControlOrMeta+V')
  const marker = await search.inputValue()
  expect(marker).toMatch(/^sceneweave-clipboard:[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/)
  for (const privateValue of [source.id, original.document.sceneId, original.document.title, '铜色桌灯', 'positionMm', 'visibility']) expect(marker).not.toContain(privateValue)
  await search.fill(source.id)
  expect((await keyboardProjectBackup(page, info.outputPath('clipboard-copied.sceneweave'))).hashes).toEqual(original.hashes)

  await paste()
  await expect(revision).toHaveAttribute('data-revision', String(original.document.revision))
  await page.screenshot({ path: info.outputPath('clipboard-preview.png') })
  await review.getByRole('button', { name: '取消批量预览', exact: true }).click()
  await expect(review).toHaveCount(0)
  expect((await keyboardProjectBackup(page, info.outputPath('clipboard-cancelled.sceneweave'))).hashes).toEqual(original.hashes)
  await paste()
  await viewport.focus()
  await viewport.press('Escape')
  await expect(review).toHaveCount(0)
  expect((await keyboardProjectBackup(page, info.outputPath('clipboard-escape.sceneweave'))).hashes).toEqual(original.hashes)

  await paste()
  await review.getByRole('button', { name: '采用批量修改', exact: true }).click()
  await expect(review).toHaveCount(0)
  await keyboardWorkspaceSaved(page)
  const adopted = await keyboardProjectBackup(page, info.outputPath('clipboard-adopted.sceneweave'))
  const copies = Object.values(adopted.document.props).filter(prop => prop.id !== source.id)
  expect(copies).toHaveLength(1)
  const [copied] = copies
  expect(adopted.document.revision).toBe(original.document.revision + 1)
  expect(adopted.document.props[source.id]).toEqual(source)
  expect(copied).toEqual({ ...source, id: copied.id, renderOrder: copied.renderOrder, positionMm: { x: 4300, y: 4300 } })
  expect(adopted.document.entityLayers[copied.id]).toBe(original.document.entityLayers[source.id])
  expect(adopted.identity.propTokens[copied.id]).toBeTruthy()
  expect(adopted.identity.propTokens[copied.id]).not.toBe(original.identity.propTokens[source.id])
  expect(adopted.appearance.propSources[copied.id]).toEqual(original.appearance.propSources[source.id])
  expect(adopted.appearance.instanceAdjustments[copied.id] ?? []).toEqual(original.appearance.instanceAdjustments[source.id] ?? [])
  expect(keyboardResourceHashes(adopted.hashes)).toEqual(keyboardResourceHashes(original.hashes))

  await viewport.focus()
  await viewport.press('ControlOrMeta+Z')
  await keyboardWorkspaceSaved(page)
  const undone = await keyboardProjectBackup(page, info.outputPath('clipboard-undone.sceneweave'))
  expect(undone.document).toEqual({ ...original.document, revision: original.document.revision + 2, updatedAt: undone.document.updatedAt })
  await viewport.focus()
  await viewport.press('ControlOrMeta+Shift+Z')
  await keyboardWorkspaceSaved(page)
  const redone = await keyboardProjectBackup(page, info.outputPath('clipboard-redone.sceneweave'))
  expect(redone.document).toEqual({ ...adopted.document, revision: original.document.revision + 3, updatedAt: redone.document.updatedAt })

  await selectKeyboardProp(page, source.id)
  await copy()
  await page.getByLabel('物件 X', { exact: true }).fill('5')
  await page.getByLabel('物件 X', { exact: true }).press('Tab')
  await keyboardWorkspaceSaved(page)
  const changed = await keyboardProjectBackup(page, info.outputPath('clipboard-source-changed.sceneweave'))
  expect(changed.document.props[source.id].positionMm.x).toBe(5000)
  await viewport.focus()
  await viewport.press('ControlOrMeta+V')
  await expect(page.locator('.asset-notice')).toContainText('复制源已改变或删除，请重新复制后粘贴')
  await expect(review).toHaveCount(0)
  await keyboardWorkspaceSaved(page)
  expect((await keyboardProjectBackup(page, info.outputPath('clipboard-stale-rejected.sceneweave'))).hashes).toEqual(changed.hashes)
  await copy()
  await paste()
  await viewport.focus()
  await viewport.press('Escape')
  await expect(review).toHaveCount(0)

  // A normal text field keeps native text copy and paste; unrelated text cannot paste objects.
  await search.fill('仅供文本复制')
  await search.press('ControlOrMeta+A')
  await search.press('ControlOrMeta+C')
  await search.fill('')
  await search.press('ControlOrMeta+V')
  await expect(search).toHaveValue('仅供文本复制')
  await viewport.focus()
  await viewport.press('ControlOrMeta+V')
  await expect(page.locator('.asset-notice')).toContainText('剪贴板中没有本次工程会话复制的物件')
  await expect(review).toHaveCount(0)
  expect((await keyboardProjectBackup(page, info.outputPath('clipboard-text-rejected.sceneweave'))).hashes).toEqual(changed.hashes)

  await selectKeyboardProp(page, source.id)
  await copy()
  await reloadSaved(page)
  await keyboardWorkspaceSaved(page)
  await viewport.focus()
  await viewport.press('ControlOrMeta+V')
  await expect(page.locator('.asset-notice')).toContainText('剪贴板中没有本次工程会话复制的物件')
  await expect(review).toHaveCount(0)
  expect((await keyboardProjectBackup(page, info.outputPath('clipboard-reopened.sceneweave'))).hashes).toEqual(changed.hashes)
  expect(errors).toEqual([])
  await info.attach('clipboard-facts.json', { body: JSON.stringify({ marker, source, copied, revisions: [original.document.revision, adopted.document.revision, undone.document.revision, redone.document.revision, changed.document.revision], errors }), contentType: 'application/json' })
})
