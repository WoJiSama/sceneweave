test('all six native palettes materialize actual PNGs and representative scenes remain editable packages', async ({ page }, info) => {
  test.setTimeout(300_000)
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await createKeyboardProject(page, '六主题源码与实际图片')
  await openWorkspaceModule(page, '素材')
  const panel = page.getByRole('region', { name: '主题素材包', exact: true })
  await panel.locator(':scope > details > summary').click()
  const facts = []
  for (const id of ['investigation', 'modern', 'fantasy', 'ruins', 'wilderness', 'coast']) {
    await panel.getByLabel('选择主题包', { exact: true }).selectOption(id)
    await panel.getByRole('button', { name: '加载所选主题包', exact: true }).click()
    await expect(panel).toContainText('已加载 6 材质、14 物件、3 组合', { timeout: 90_000 })
    await expect.poll(() => panel.locator('img').evaluateAll(images => images.length === 23 && images.every(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
    const dimensions = await panel.locator('img').evaluateAll(images => images.map(image => ({ name: image.getAttribute('alt'), width: (image as HTMLImageElement).naturalWidth, height: (image as HTMLImageElement).naturalHeight })))
    await panel.screenshot({ path: info.outputPath(`palette-${id}.png`) })
    const scenarios = panel.getByText('两份可编辑代表场景', { exact: true })
    const disclosure = scenarios.locator('..')
    if (await disclosure.getAttribute('open') === null) await scenarios.click()
    const buttons = panel.getByRole('button', { name: /^下载场景 ·/ })
    for (let index = 0; index < 2; index++) {
      const downloading = page.waitForEvent('download')
      await buttons.nth(index).click()
      const sample = await downloading; await sample.saveAs(info.outputPath(`${id}-sample-${index + 1}.sceneweave`))
      expect((await readFile(info.outputPath(`${id}-sample-${index + 1}.sceneweave`))).length).toBeGreaterThan(1000)
      await expect(panel.getByRole('button', { name: '加载所选主题包', exact: true })).toBeEnabled()
    }
    facts.push({ id, images: dimensions, actualEditablePackages: 2 })
  }
  expect(errors).toEqual([])
  await writeFile(info.outputPath('palette-facts.json'), JSON.stringify({ facts, errors }, null, 2))
})

test('indoor and coastal theme samples open as editable scenes and export real maps', async ({ page, browser }, info) => {
  test.setTimeout(180_000)
  await createKeyboardProject(page, '代表场景交付')
  await openWorkspaceModule(page, '素材')
  const panel = page.getByRole('region', { name: '主题素材包', exact: true })
  await panel.locator(':scope > details > summary').click()
  await panel.getByText('两份可编辑代表场景', { exact: true }).click()
  for (const id of ['investigation', 'coast']) {
    await panel.getByLabel('选择主题包', { exact: true }).selectOption(id)
    const downloading = page.waitForEvent('download')
    await panel.getByRole('button', { name: /^下载场景 ·/ }).first().click()
    const sample = await downloading; await sample.saveAs(info.outputPath(`${id}.sceneweave`))
    const context = await browser.newContext()
    try {
      const target = await context.newPage(); await target.goto(new URL('./#home', page.url()).href)
      const choosing = target.waitForEvent('filechooser')
      await target.getByTestId('workspace-home').getByRole('button', { name: '打开工程文件', exact: true }).click()
      await (await choosing).setFiles(info.outputPath(`${id}.sceneweave`)); await keyboardWorkspaceSaved(target)
      const opened = await keyboardProjectBackup(target, info.outputPath(`${id}-opened.sceneweave`))
      const memberIds = new Set(Object.values(opened.document.prefabInstances).flatMap(prefab => Object.values(prefab.members).map(member => member.propId)))
      const prop = Object.values(opened.document.props).find(prop => !memberIds.has(prop.id))!
      expect(prop).toBeTruthy()
      await selectKeyboardProp(target, prop.id)
      const inspector = await openKeyboardPanel(target, 'inspector')
      await inspector.getByLabel('物件 X', { exact: true }).fill(String((prop.positionMm.x + 1) / 1000))
      await inspector.getByLabel('物件 X', { exact: true }).press('Enter'); await keyboardWorkspaceSaved(target)
      const edited = await keyboardProjectBackup(target, info.outputPath(`${id}-edited.sceneweave`))
      expect(edited.document.props[prop.id].positionMm.x).toBe(prop.positionMm.x + 1)
      await target.getByRole('button', { name: '撤销编辑', exact: true }).click(); await keyboardWorkspaceSaved(target)
      const undone = await keyboardProjectBackup(target, info.outputPath(`${id}-undone.sceneweave`))
      expect(undone.document.props).toEqual(opened.document.props)
      const exporting = target.waitForEvent('download')
      await (await mapExportButton(target, 'player')).click()
      await (await exporting).saveAs(info.outputPath(`${id}-player.png`))
      const png = await readFile(info.outputPath(`${id}-player.png`)); expect(png.readUInt32BE(16)).toBe(4096)
      await target.locator('.workspace-export-menu > summary').click()
      await target.screenshot({ path: info.outputPath(`${id}-editable.png`) })
    } finally { await context.close() }
    await expect(panel.getByRole('button', { name: '加载所选主题包', exact: true })).toBeEnabled()
  }
})
